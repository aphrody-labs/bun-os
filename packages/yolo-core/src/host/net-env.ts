// The private network map of <aphrody home>/private/network.env: a generated block rendered from the tunnel
// declaration (members, services, grants, mesh, the fallback reverse tunnel), live reachability probes from the
// local member and the SSH_CONFIG mirror of ~/.ssh/config. Secrets already in the file are never read out or printed:
// only the generated block is replaced, everything around it is kept byte for byte.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { buildFiche, syncFicheWith, writeMemory } from "./fiche.ts";
import { collectFacts, renderFacts, setKeys, staticUpdates } from "./net-facts.ts";
import { ufwRules, type Tunnel } from "./wireguard.ts";

export const BEGIN = "# >>> aphrody-net-map (generated by `host/cli.ts net-env`, edits are overwritten)";
export const END = "# <<< aphrody-net-map";

const key = (s: string) => s.toUpperCase().replace(/[^A-Z0-9]+/g, "_");

export function networkEnvPath(env = process.env): string {
  return join(env.APHRODY_HOME ?? join(homedir(), ".aphrody"), "private", "network.env");
}

const addressOf = (t: Tunnel, id: string) =>
  id === t.hub.peer ? t.hub.address : t.peers.find(p => p.id === id)?.address;

/** What `member` may reach: granted services, then every member it meshes with (all ports). */
export function reachable(t: Tunnel, member: string) {
  const byId = new Map(t.services.map(s => [s.id, s]));
  const services = (t.grants[member] ?? [])
    .map(id => byId.get(id))
    .filter((s): s is NonNullable<typeof s> => !!s && s.port !== undefined && s.status !== "pending");
  const mesh = [...new Set((t.mesh ?? []).filter(m => m.from.includes(member)).flatMap(m => m.to))]
    .filter(id => id !== member)
    .map(id => ({ id, address: addressOf(t, id)! }))
    .filter(m => m.address);
  return { services, mesh };
}

export interface Probe {
  name: string;
  target: string;
  ok: boolean;
  ms: number;
}

/** The generated block: no secret, only addresses, ports, grants and the probe results when given. */
export function renderNetMap(
  t: Tunnel,
  member: string,
  probes?: Probe[],
  now = new Date(),
  live: string[] = [],
): string {
  const lines = [BEGIN, `NET_MAP_GENERATED=${now.toISOString()}`, `NET_SELF=${member}`];
  lines.push(`NET_INTERFACE=${t.interface}`, `NET_WINDOWS_TUNNEL=${t.windowsTunnelName}`);
  lines.push(`NET_SUBNET=${t.subnet}`, `NET_HUB=${t.hub.peer}@${t.hub.address} ${t.hub.endpoint}`);
  const members = [t.hub.peer, ...t.peers.map(p => p.id)];
  lines.push(`NET_MEMBERS=${members.join(",")}`);
  for (const id of members) lines.push(`NET_${key(id)}_ADDRESS=${addressOf(t, id)}`);
  for (const s of t.services)
    lines.push(`NET_SERVICE_${key(s.id)}=${s.address}:${s.port ?? "pending"} ${s.expose}${s.auth ? ` ${s.auth}` : ""}`);
  for (const [peer, ids] of Object.entries(t.grants)) lines.push(`NET_GRANT_${key(peer)}=${ids.join(",")}`);
  for (const m of t.mesh ?? [])
    lines.push(`NET_MESH_${key(m.id)}=${m.from.join(",")} -> ${m.to.join(",")} (all ports)`);
  if (t.firewall.meshDenied?.length) lines.push(`NET_MESH_DENIED=${t.firewall.meshDenied.join(",")}`);
  lines.push(`NET_HUB_UFW_RULES=${ufwRules(t).length}`);
  const own = reachable(t, member);
  lines.push(`NET_REACH_SERVICES=${own.services.map(s => `${s.id}=${s.address}:${s.port}`).join(" ")}`);
  lines.push(`NET_REACH_MESH=${own.mesh.map(m => `${m.id}=${m.address}`).join(" ")}`);
  if (probes) {
    lines.push(`NET_STATUS_AT=${now.toISOString()}`);
    for (const p of probes) lines.push(`NET_STATUS_${key(p.name)}=${p.ok ? "up" : "down"} ${p.target} ${p.ms}ms`);
    lines.push(`NET_STATUS_UP=${probes.filter(p => p.ok).length}/${probes.length}`);
  }
  lines.push(...live, END);
  return lines.join("\n");
}

/** Replace the generated block of `text` (or append it); the rest of the file is kept unchanged. */
export function mergeNetMap(text: string, block: string): string {
  const start = text.indexOf(BEGIN);
  const stop = text.indexOf(END);
  if (start >= 0 && stop > start) return text.slice(0, start) + block + text.slice(stop + END.length);
  return `${text.replace(/\s*$/, "")}\n\n${block}\n`;
}

export async function tcp(host: string, port: number, timeoutMs: number): Promise<boolean> {
  return await new Promise<boolean>(resolve => {
    const timer = setTimeout(() => resolve(false), timeoutMs);
    Bun.connect({
      hostname: host,
      port,
      socket: {
        open(s) {
          clearTimeout(timer);
          s.end();
          resolve(true);
        },
        connectError() {
          clearTimeout(timer);
          resolve(false);
        },
        data() {},
      },
    }).catch(() => {
      clearTimeout(timer);
      resolve(false);
    });
  });
}

/** TCP probes of every service granted to `member`, plus SSH on every member it meshes with. */
export async function probeNetwork(t: Tunnel, member: string, timeoutMs = 2500): Promise<Probe[]> {
  const own = reachable(t, member);
  const jobs = [
    ...own.services.map(s => ({
      name: s.id,
      host: s.address,
      port: s.port!,
    })),
    ...own.mesh
      .filter(m => !own.services.some(s => s.address === m.address && s.port === 22))
      .map(m => ({ name: `mesh-${m.id}-ssh`, host: m.address, port: 22 })),
  ];
  return await Promise.all(
    jobs.map(async j => {
      const started = performance.now();
      const ok = await tcp(j.host, j.port, timeoutMs);
      return {
        name: j.name,
        target: `${j.host}:${j.port}`,
        ok,
        ms: Math.round(performance.now() - started),
      };
    }),
  );
}

/** The quoted multi-line value of `name` in a dotenv text. */
export function envValue(text: string, name: string): string | undefined {
  const m = new RegExp(`^${name}=(?:"([\\s\\S]*?)"|(.*))$`, "m").exec(text);
  return m ? (m[1] ?? m[2]) : undefined;
}

/** Mirror ~/.ssh/config into the SSH_CONFIG value of network.env (the live file is the source). */
export function captureSshConfig(envText: string, file = join(homedir(), ".ssh", "config")): string {
  const live = readFileSync(file, "utf8").replace(/\r\n/g, "\n").trimEnd().replaceAll('"', "'");
  const line = `SSH_CONFIG="${live}"`;
  const re = /^SSH_CONFIG=(?:"[\s\S]*?"|.*)$/m;
  return re.test(envText) ? envText.replace(re, () => line) : `${envText.trimEnd()}\n${line}\n`;
}

/** Send only the NET_LIVE_* lines (no secret) to `host` over SSH, atomically, for the hub synchronisation. */
export async function pushLive(lines: string[], host: string, path: string): Promise<boolean> {
  const proc = Bun.spawn(
    [
      "ssh",
      "-o",
      "BatchMode=yes",
      "-o",
      "ConnectTimeout=8",
      host,
      `mkdir -p "$(dirname ${path})" && cat > ${path}.tmp && mv ${path}.tmp ${path}`,
    ],
    { stdin: "pipe", stdout: "ignore", stderr: "ignore", timeout: 20_000 },
  );
  proc.stdin.write(lines.filter(l => l.startsWith("NET_LIVE_")).join("\n") + "\n");
  await proc.stdin.end();
  return (await proc.exited) === 0;
}

/** `net-env [--member M] [--probe] [--facts] [--write [--ssh-config]] [--push HOST [--push-path P]] [--fiche HOST [--fiche-memory F]] [--file F]`: prints the block unless --write. */
export async function netEnvMain(t: Tunnel, args: string[]): Promise<void> {
  const value = (name: string) => {
    const at = args.indexOf(`--${name}`);
    return at >= 0 ? args[at + 1] : undefined;
  };
  const file = value("file") ?? networkEnvPath();
  const member = value("member") ?? "aphro-pc";
  if (!addressOf(t, member)) throw new Error(`unknown member ${member}`);
  const probes = args.includes("--probe") ? await probeNetwork(t, member) : undefined;
  const collected = args.includes("--facts") ? await collectFacts(t, member, tcp) : undefined;
  const block = renderNetMap(t, member, probes, new Date(), collected ? renderFacts(collected) : []);
  if (!args.includes("--write")) console.log(block);
  else {
    const text = existsSync(file) ? readFileSync(file, "utf8") : "";
    const merged = mergeNetMap(text, block);
    writeFileSync(file, collected ? setKeys(merged, staticUpdates(collected.publicIps)) : merged);
    console.log(`net-env: ${file} updated${probes ? ` (${probes.filter(p => p.ok).length}/${probes.length} up)` : ""}`);
  }
  const pushHost = value("push");
  if (pushHost && collected) {
    const ok = await pushLive(
      renderFacts(collected),
      pushHost,
      value("push-path") ?? "~/.local/state/aphrody-sync/net-live.env",
    );
    console.log(`push: ${pushHost} ${ok ? "ok" : "failed"}`);
  }
  const ficheHost = value("fiche");
  if (ficheHost && args.includes("--write")) {
    const merged = await syncFicheWith(ficheHost, await buildFiche(process.cwd(), file));
    const memory = value("fiche-memory");
    if (merged && memory) writeMemory(memory, merged);
    console.log(`fiche: ${ficheHost} ${merged ? "ok" : "failed"}`);
  }
  if (args.includes("--ssh-config") && args.includes("--write")) {
    const before = readFileSync(file, "utf8");
    const after = captureSshConfig(before);
    if (after !== before) writeFileSync(file, after);
    console.log(`ssh-config: ${after === before ? "unchanged" : "captured from ~/.ssh/config"}`);
  }
  if (probes) for (const p of probes) if (!p.ok) console.error(`down: ${p.name} ${p.target}`);
}
