// Output formats generated from the resolved model: CSS variables, Tailwind v4 theme, TypeScript data,
// Rust consts, Tauri window-effect settings. Pure functions: build.ts writes the files, tests snapshot them.
import { parseHex } from "./color.ts";
import {
  SCHEMES,
  SLOTS,
  THEME_IDS,
  type Model,
  type Resolved,
  type Scheme,
  type Slot,
  type ThemeId,
  type ThemeStatic,
} from "./resolve.ts";

const kebab = (s: string) => s.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`);
const snake = (s: string) => s.replace(/[A-Z]/g, c => `_${c.toLowerCase()}`).replace(/-/g, "_");
const slotVar = (s: Slot) => `--t-${kebab(s)}`;
const bezier = (e: number[]) => `cubic-bezier(${e.join(", ")})`;
const HEADER = "Generated by packages/themes/src/build.ts from packages/themes/tokens/*.tokens.json. Do not edit.";

// The contract ramp every theme answers to (components.css reads these), mapped to the theme's native styles.
const ALIAS: Record<ThemeId, Record<string, string>> = {
  m3: {
    caption: "body-small",
    body: "body-medium",
    "body-strong": "label-large",
    subtitle: "title-medium",
    title: "headline-small",
    display: "display-small",
  },
  apple: {
    caption: "caption1",
    "body-strong": "headline",
    subtitle: "title3",
    title: "title1",
    display: "largeTitle",
  },
  fluent: {},
};
function rampVars(s: ThemeStatic, ramp: ThemeStatic["ramp"]): Record<string, string> {
  const o: Record<string, string> = {};
  const put = (name: string, t: { size: number; line: number; weight: number }) => {
    o[`--t-text-${name}-size`] = `${t.size}px`;
    o[`--t-text-${name}-line`] = `${t.line}px`;
    o[`--t-text-${name}-weight`] = `${t.weight}`;
  };
  for (const [k, t] of Object.entries(ramp)) put(kebab(k), t);
  for (const [name, from] of Object.entries(ALIAS[s.id])) {
    const src = ramp[from] ?? ramp[from.replace(/-([a-z])/g, (_, c) => c.toUpperCase())];
    if (!src) throw new Error(`ramp alias ${name} -> ${from} missing in ${s.id}`);
    put(name, src);
  }
  return o;
}

function staticVars(s: ThemeStatic): Record<string, string> {
  const o: Record<string, string> = {};
  for (const [k, px] of Object.entries(s.shape)) o[`--t-radius-${kebab(k)}`] = `${px}px`;
  o["--t-font-ui"] = s.fonts.ui;
  o["--t-font-display"] = s.fonts.display;
  o["--t-font-mono"] = s.fonts.mono;
  Object.assign(o, rampVars(s, s.ramp));
  o["--t-motion-fast"] = `${s.motion.fastMs}ms`;
  o["--t-motion-normal"] = `${s.motion.normalMs}ms`;
  o["--t-motion-slow"] = `${s.motion.slowMs}ms`;
  o["--t-motion-easing"] = bezier(s.motion.easing);
  o["--t-glass-blur"] = `${s.glass.blur}px`;
  o["--t-glass-saturate"] = `${s.glass.saturate}%`;
  o["--t-glass-bg"] = "color-mix(in srgb, var(--t-glass-tint) calc(var(--t-glass-opacity) * 100%), transparent)";
  return o;
}

function colorVars(r: Resolved, s: ThemeStatic): Record<string, string> {
  const o: Record<string, string> = {};
  for (const k of SLOTS) if (k !== "glass") o[slotVar(k)] = r.colors[k];
  o["--t-glass-opacity"] = String(s.glass.opacity[r.scheme]);
  return { ...o, ...r.extra };
}

const block = (sel: string, vars: Record<string, string>) =>
  `${sel} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n")}\n}\n`;

export function themesCss(m: Model, components: string): string {
  let out = `/* ${HEADER} */\n/* Switch with <html data-skin="m3|fluent|apple" data-scheme="light|dark" data-accent="..."> (see runtime.ts). Without data-scheme the light scheme applies. */\n`;
  for (const id of THEME_IDS) {
    const s = m.statics[id];
    out += block(`[data-skin="${id}"]`, {
      ...staticVars(s),
      "color-scheme": "light dark",
    });
    if (id === "apple" && s.rampDesktop) {
      const d = rampVars(s, s.rampDesktop);
      out += `@media (pointer: fine) {\n${block(`[data-skin="apple"]`, d).replace(/^/gm, "  ").replace(/ +\n/g, "\n")}}\n`;
    }
    for (const scheme of SCHEMES) {
      const rs = m.resolved.filter(r => r.theme === id && r.scheme === scheme);
      const base = rs.find(r => r.accent === s.defaultAccent)!;
      const baseVars = colorVars(base, s);
      const baseSel =
        scheme === "dark" ? `[data-skin="${id}"][data-scheme="dark"]` : `[data-skin="${id}"]:not([data-scheme="dark"])`;
      out += block(baseSel, { ...baseVars, "color-scheme": scheme });
      for (const r of rs) {
        if (r === base) continue;
        const vars = colorVars(r, s);
        const diff = Object.fromEntries(Object.entries(vars).filter(([k, v]) => baseVars[k] !== v));
        out += block(`${baseSel}[data-accent="${r.accent}"]`, diff);
      }
    }
  }
  return out + "\n" + components;
}

export function tailwindCss(): string {
  const lines = SLOTS.map(k => `  --color-${kebab(k)}: var(${k === "glass" ? "--t-glass-bg" : slotVar(k)});`);
  return `/* ${HEADER} */
/* Tailwind v4: @import "tailwindcss"; @import "@aphrody/themes/themes.css"; @import "@aphrody/themes/tailwind.css"; */
@theme inline {
${lines.join("\n")}
  --font-sans: var(--t-font-ui);
  --font-display: var(--t-font-display);
  --font-mono: var(--t-font-mono);
  --radius-sm: var(--t-radius-sm);
  --radius-md: var(--t-radius-md);
  --radius-lg: var(--t-radius-lg);
  --radius-xl: var(--t-radius-xl);
  --radius-control: var(--t-radius-control);
  --radius-container: var(--t-radius-container);
  --ease-theme: var(--t-motion-easing);
  --default-transition-duration: var(--t-motion-normal);
  --default-transition-timing-function: var(--t-motion-easing);
}
@utility glass {
  background: var(--t-glass-bg);
  backdrop-filter: blur(var(--t-glass-blur)) saturate(var(--t-glass-saturate));
  border: 1px solid var(--t-glass-border);
  box-shadow: inset 0 1px 0 var(--t-glass-highlight);
}
`;
}

export function windowEffects(m: Model): Record<string, unknown> {
  const out: Record<string, unknown> = {
    $comment: `${HEADER} Effect names are tauri-utils WindowEffect (camelCase) as of tauri 2.12.5.`,
  };
  for (const id of THEME_IDS) {
    const s = m.statics[id];
    const w = s.windowEffects;
    const glass = id === "apple";
    out[id] = {
      windows: {
        effects: w.windows,
        transparent: w.windows.length > 0 || glass,
        cssBlurFallback: glass,
        windowTheme: "follow-scheme",
      },
      macos: {
        effects: w.macos,
        radius: s.shape.container,
        state: "followsWindowActiveState",
        transparent: w.macos.length > 0,
        titleBarStyle: id === "apple" ? "Overlay" : "Visible",
        interactive: id === "apple",
      },
      other: { effects: w.other, transparent: glass, cssBlurFallback: glass },
      controls: s.controls,
    };
  }
  return out;
}

export function generatedTs(m: Model): string {
  const colors: Record<string, Record<string, Record<string, Record<string, string>>>> = {};
  for (const r of m.resolved) ((colors[r.theme] ??= {})[r.scheme] ??= {})[r.accent] = r.colors;
  const meta = Object.fromEntries(THEME_IDS.map(id => [id, m.statics[id]]));
  return `// ${HEADER}
export const SLOTS = ${JSON.stringify(SLOTS)} as const;
export type Slot = (typeof SLOTS)[number];
export const THEME_IDS = ${JSON.stringify(THEME_IDS)} as const;
export type ThemeId = (typeof THEME_IDS)[number];
export type Scheme = "light" | "dark";

export interface TextStyle { size: number; line: number; weight: number }
export interface ThemeMeta {
  id: ThemeId;
  name: string;
  accents: string[];
  defaultAccent: string;
  shape: Record<string, number>;
  fonts: { ui: string; display: string; mono: string };
  ramp: Record<string, TextStyle>;
  rampDesktop?: Record<string, TextStyle>;
  motion: { fastMs: number; normalMs: number; slowMs: number; easing: [number, number, number, number] };
  glass: { blur: number; saturate: number; opacity: Record<Scheme, number> };
  controls: "traffic-lights" | "caption" | "m3";
  windowEffects: { windows: string[]; macos: string[]; other: string[] };
  unknown: string[];
}

export const META: Record<ThemeId, ThemeMeta> = ${JSON.stringify(meta, (k, v) => (k === "sources" || k === "springs" ? undefined : v), 2)};

/** COLORS[theme][scheme][accent][slot], #RRGGBB or #RRGGBBAA. */
export const COLORS: Record<ThemeId, Record<Scheme, Record<string, Record<Slot, string>>>> = ${JSON.stringify(
    colors,
    undefined,
    1,
  )};
`;
}

const rs = (hex: string) => {
  const c = parseHex(hex);
  return `Rgba::new(${c.r}, ${c.g}, ${c.b}, ${Math.round(c.a * 255)})`;
};
const f = (n: number) => (Number.isInteger(n) ? `${n}.0` : `${n}`);
const pascal = (s: string) => s.replace(/(^|[-_ ])(\w)/g, (_, __, c) => c.toUpperCase());

export function generatedRs(m: Model): string {
  const slots = SLOTS;
  let o = `// ${HEADER}\n#![allow(clippy::all)]\nuse crate::{Palette, Rgba, Scheme, TextStyle, ThemeId, ThemeMeta, Controls, Radii, Motion, Glass, WindowEffects, Fonts};\n\n`;
  const ent: string[] = [];
  for (const r of m.resolved) {
    const name = `${r.theme}_${r.scheme}_${r.accent}`.toUpperCase();
    o += `static ${name}: Palette = Palette {\n${slots.map(k => `    ${snake(k)}: ${rs(r.colors[k])},`).join("\n")}\n};\n`;
    ent.push(`    (ThemeId::${pascal(r.theme)}, Scheme::${pascal(r.scheme)}, "${r.accent}", &${name}),`);
  }
  o += `\n/// Every resolved palette: (theme, scheme, accent).\npub static PALETTES: &[(ThemeId, Scheme, &str, &Palette)] = &[\n${ent.join("\n")}\n];\n\n`;
  const style = (k: string, t: { size: number; line: number; weight: number }) =>
    `("${k}", TextStyle { size: ${f(t.size)}, line: ${f(t.line)}, weight: ${t.weight} })`;
  const get = (s: ThemeStatic, k: string) => f(s.shape[k] ?? 0);
  const metas = THEME_IDS.map(id => {
    const s = m.statics[id];
    const ctl = s.controls === "traffic-lights" ? "TrafficLights" : s.controls === "caption" ? "Caption" : "M3";
    const list = (a: string[]) => `&[${a.map(x => `"${x}"`).join(", ")}]`;
    return `static ${id.toUpperCase()}_META: ThemeMeta = ThemeMeta {
    id: ThemeId::${pascal(id)},
    name: ${JSON.stringify(s.name)},
    accents: &[${s.accents.map(a => `"${a}"`).join(", ")}],
    default_accent: "${s.defaultAccent}",
    radii: Radii { none: ${get(s, "none")}, sm: ${get(s, "sm")}, md: ${get(s, "md")}, lg: ${get(s, "lg")}, xl: ${get(s, "xl")}, full: ${get(s, "full")}, control: ${get(s, "control")}, container: ${get(s, "container")} },
    fonts: Fonts { ui: ${JSON.stringify(s.fonts.ui)}, display: ${JSON.stringify(s.fonts.display)}, mono: ${JSON.stringify(s.fonts.mono)} },
    ramp: &[${Object.entries(s.ramp)
      .map(([k, t]) => style(k, t))
      .join(", ")}],
    ramp_desktop: &[${Object.entries(s.rampDesktop ?? {})
      .map(([k, t]) => style(k, t))
      .join(", ")}],
    motion: Motion { fast_ms: ${f(s.motion.fastMs)}, normal_ms: ${f(s.motion.normalMs)}, slow_ms: ${f(s.motion.slowMs)}, easing: [${s.motion.easing.map(f).join(", ")}] },
    glass: Glass { blur: ${f(s.glass.blur)}, saturate: ${f(s.glass.saturate)}, opacity_light: ${f(s.glass.opacity.light)}, opacity_dark: ${f(s.glass.opacity.dark)} },
    controls: Controls::${ctl},
    window_effects: WindowEffects { windows: ${list(s.windowEffects.windows)}, macos: ${list(s.windowEffects.macos)}, other: ${list(s.windowEffects.other)} },
};`;
  });
  o +=
    metas.join("\n") +
    `\n\n/// Static metadata of every theme.\npub static METAS: &[&ThemeMeta] = &[&M3_META, &FLUENT_META, &APPLE_META];\n`;
  return o;
}

export function resolvedJson(m: Model): string {
  const colors: Record<string, unknown> = {};
  for (const r of m.resolved) {
    const t = (colors[r.theme] ??= {}) as Record<string, Record<string, unknown>>;
    (t[r.scheme] ??= {})[r.accent] = r.colors;
  }
  const themes = Object.fromEntries(THEME_IDS.map(id => [id, m.statics[id]]));
  return JSON.stringify({ $comment: HEADER, themes, colors }, null, 1) + "\n";
}

