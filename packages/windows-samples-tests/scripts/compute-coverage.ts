#!/usr/bin/env bun
/**
 * Computes the coverage of the matrix and writes docs/WINDOWS-SAMPLES.md (every number comes from this script).
 *   bun packages/windows-samples-tests/scripts/compute-coverage.ts [--check]
 * --check fails when the committed document differs from what the recorded results produce.
 */
import { join } from "node:path";
import { compute, load, LANGS, root, STATUSES, type Status } from "../src/coverage.ts";

const inp = await load();
const c = compute(inp);
const pinsFile = await Bun.file(join(root, "vendor/microsoft/PINS.json")).json();
const sym: Record<Status, string> = { "not-started": "-", builds: "B", "runs-headless": "R", "runs-interactive-only-CI-or-manual": "I" };
const label = { cpp: "C++", cs: "C#", rust: "Rust", bun: "Bun" } as const;

const L: string[] = [];
L.push("# Windows samples test matrix", "");
L.push("Generated by `packages/windows-samples-tests/scripts/compute-coverage.ts` from `manifest/coverage.json` and the recorded build/run results; do not edit by hand.", "");
L.push(`Results observed ${inp.impls ? "on this Windows 11 host (VS Build Tools 14.51, SDK 10.0.26100, .NET 10.0.403 and 11.0.100-rc.3, Rust nightly-2026-09-15, Bun canary)" : ""}.`, "");
L.push("Cell legend: `-` not-started, `B` builds, `R` runs-headless, `I` runs-interactive-only-CI-or-manual (built; needs a window or a user, so only CI/manual can run it).", "");

L.push("## Pinned references (vendor/microsoft)", "", "| Submodule | Pin | Commit | Date | Size (KB) | Prerelease seen |", "|---|---|---|---|---|---|");
for (const [name, p] of Object.entries<any>(pinsFile.pins))
  L.push(`| ${name} | ${p.ref} | \`${p.sha.slice(0, 12)}\` | ${p.commitDate.slice(0, 10)} | ${p.sizeKB} | ${p.prerelease ? `${p.prerelease.tag} (\`${p.prerelease.sha.slice(0, 12)}\`)` : "-"} |`);
L.push("");

L.push("## Coverage per language", "", "Percentages are computed over all rows (denominator = " + inp.manifest.rows.length + "). The functional columns exclude the " + Object.values(inp.manifest.rows).filter(r => r.cells.cpp.impl?.startsWith("xaml-static")).length + " WinUI Gallery rows, whose implementations only scan the XAML statically (they do not instantiate WinUI controls).", "");
L.push("| Language | not-started | builds | runs-headless | interactive-only | implemented % | runs-headless % | functional implemented % | functional runs-headless % |", "|---|---|---|---|---|---|---|---|---|");
for (const l of LANGS) {
  const p = c.perLang[l];
  L.push(`| ${label[l]} | ${STATUSES.map(s => p.counts[s]).join(" | ")} | ${p.implementedPct} | ${p.runsHeadlessPct} | ${p.functionalImplementedPct} | ${p.functionalRunsPct} |`);
}
L.push("");

L.push("## Coverage per category (implemented / rows; runs-headless in brackets)", "", "| Category | Rows | " + LANGS.map(l => label[l]).join(" | ") + " |", "|---|---|" + LANGS.map(() => "---").join("|") + "|");
for (const [cat, n] of Object.entries(c.categoryRows)) {
  const cells = LANGS.map(l => {
    const k = c.perCategory[cat]![l];
    return `${n - k["not-started"]} (${k["runs-headless"]})`;
  });
  L.push(`| ${cat} | ${n} | ${cells.join(" | ")} |`);
}
L.push("");

L.push("## Implementations", "", "| Id | Language | Sources | Scope | Build | Run |", "|---|---|---|---|---|---|");
for (const [id, r] of Object.entries<any>(inp.impls)) L.push(`| ${id} | ${label[r.lang as keyof typeof label]} | \`${r.dir}\` | ${r.scope} | ${r.build ? "ok" : "FAIL"} | ${r.run === undefined ? "-" : r.run ? "ok" : "FAIL"} |`);
L.push("", "The C# column of the .NET rows is the official template output of `dotnet new` (generated by `scripts/generate-dotnet-templates.ts` into `examples/windows/dotnet10` and `examples/windows/dotnet11`, built with buncc's dotnet provider arguments); NativeAOT rows are published with `aotPublishArgs`.", "");

L.push("## Rows", "");
let cat = "";
for (const row of inp.manifest.rows) {
  if (row.category !== cat) {
    cat = row.category;
    L.push("", `### ${cat}`, "", "| Row | C++ | C# | Rust | Bun |", "|---|---|---|---|---|");
  }
  L.push(`| ${row.id} | ${LANGS.map(l => sym[c.statuses[row.id]![l]]).join(" | ")} |`);
}
L.push("");
const text = L.join("\n");
const target = join(root, "docs/WINDOWS-SAMPLES.md");
if (Bun.argv.includes("--check")) {
  const cur = (await Bun.file(target).exists()) ? await Bun.file(target).text() : "";
  if (cur !== text) {
    console.error("docs/WINDOWS-SAMPLES.md is stale; run compute-coverage.ts");
    process.exit(1);
  }
} else {
  await Bun.write(target, text);
  await Bun.write(join(import.meta.dir, "../manifest/computed.json"), JSON.stringify({ perLang: c.perLang, categoryRows: c.categoryRows }, null, 1) + "\n");
}
console.log(JSON.stringify(c.perLang, null, 1));
