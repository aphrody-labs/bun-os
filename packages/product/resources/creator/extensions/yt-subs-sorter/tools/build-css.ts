// Regenerates the two token sheets of the extension from the generated Aphrody brand sheet
// (packages/app-ui/src/brand.css, product seed, standard and high contrast, light and dark):
//   src/yss-tokens.css   --yss-* values of the content script UI, light and YouTube dark (html[dark])
//   popup/tokens.css     --md-sys-color-* roles of the popup, switched by prefers-color-scheme
// The extension cannot load workspace packages at run time, so the roles are copied here at build time.
// Run: bun tools/build-css.ts (or --check to fail when a sheet is stale).
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const brandPath = join(
  root,
  "..",
  "..",
  "..",
  "..",
  "..",
  "app-ui",
  "src",
  "brand.css",
);

type Roles = Map<string, string>;
type Schemes = { light: Roles; dark: Roles; lightHigh: Roles; darkHigh: Roles };

/** The four role blocks of brand.css: `:root.light, .light` and `:root, .dark`, standard then high contrast. */
export function brandSchemes(css: string): Schemes {
  const high = css.indexOf("@media (prefers-contrast: more)");
  if (high < 0) throw new Error("brand.css: no prefers-contrast block");
  const blocks: { at: number; light: boolean; roles: Roles }[] = [];
  for (const m of css.matchAll(
    /(:root\.light,\s*\.light|:root,\s*\.dark)\s*\{([^}]*)\}/g,
  )) {
    const roles: Roles = new Map();
    for (const d of m[2]!.matchAll(/(--md-sys-color-[a-z-]+):\s*([^;]+);/g))
      roles.set(d[1]!, d[2]!.trim());
    blocks.push({
      at: m.index!,
      light: m[1]!.startsWith(":root.light"),
      roles,
    });
  }
  const pick = (light: boolean, contrast: boolean) => {
    const block = blocks.find(
      (b) => b.light === light && b.at > high === contrast,
    );
    if (!block)
      throw new Error(
        `brand.css: missing ${light ? "light" : "dark"}${contrast ? " high-contrast" : ""} block`,
      );
    return block.roles;
  };
  return {
    light: pick(true, false),
    dark: pick(false, false),
    lightHigh: pick(true, true),
    darkHigh: pick(false, true),
  };
}

const role = (roles: Roles, name: string): string => {
  const value = roles.get(`--md-sys-color-${name}`);
  if (!value) throw new Error(`brand.css: no --md-sys-color-${name}`);
  return value;
};

/** --yss-* slot -> M3 role. Derived slots (chip hover, translucent lines) are color-mix()es in content.css. */
const YSS: Record<string, string> = {
  fg: "on-surface",
  "fg-dim": "on-surface-variant",
  bg: "surface-container",
  chip: "surface-container-highest",
  on: "primary",
  "on-fg": "on-primary",
  line: "outline-variant",
  field: "outline",
  focus: "secondary",
  error: "error",
  shadow: "shadow",
};

const decls = (entries: [string, string][], indent: string) =>
  entries.map(([k, v]) => `${indent}${k}: ${v};`).join("\n");
const yss = (roles: Roles, indent: string) =>
  decls(
    Object.entries(YSS).map(([slot, name]) => [
      `--yss-${slot}`,
      role(roles, name),
    ]),
    indent,
  );
const md = (roles: Roles, indent: string) => decls([...roles], indent);

const header = (what: string) => `/* SPDX-License-Identifier: Apache-2.0 */
/* ${what}, generated by tools/build-css.ts from packages/app-ui/src/brand.css. Do not hand-edit: run bun tools/build-css.ts. */
`;

export function contentTokens(s: Schemes): string {
  return `${header("YouTube Subs Sorter content-script tokens")}
.yss-ui {
${yss(s.light, "  ")}
}

html[dark] .yss-ui {
${yss(s.dark, "  ")}
}

@media (prefers-contrast: more) {
  .yss-ui {
${yss(s.lightHigh, "    ")}
  }

  html[dark] .yss-ui {
${yss(s.darkHigh, "    ")}
  }
}
`;
}

export function popupTokens(s: Schemes): string {
  return `${header("YouTube Subs Sorter popup roles")}
:root {
  color-scheme: light dark;
}

@media (prefers-color-scheme: light) {
  :root {
${md(s.light, "    ")}
  }
}

@media (prefers-color-scheme: dark) {
  :root {
${md(s.dark, "    ")}
  }
}

@media (prefers-contrast: more) and (prefers-color-scheme: light) {
  :root {
${md(s.lightHigh, "    ")}
  }
}

@media (prefers-contrast: more) and (prefers-color-scheme: dark) {
  :root {
${md(s.darkHigh, "    ")}
  }
}
`;
}

if (import.meta.main) {
  const schemes = brandSchemes(await Bun.file(brandPath).text());
  const outputs: [string, string][] = [
    [join(root, "src", "yss-tokens.css"), contentTokens(schemes)],
    [join(root, "popup", "tokens.css"), popupTokens(schemes)],
  ];
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [path, css] of outputs) {
    if (check) {
      if (
        (await Bun.file(path)
          .text()
          .catch(() => "")) !== css
      ) {
        console.error(`stale: ${path} (run bun tools/build-css.ts)`);
        stale++;
      }
    } else {
      await Bun.write(path, css);
      console.log(`wrote ${path}`);
    }
  }
  if (stale) process.exit(1);
}
