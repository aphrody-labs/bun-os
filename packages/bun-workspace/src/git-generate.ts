/**
 * Generators for repository-level git metadata: .gitattributes managed block, .github/CODEOWNERS (from
 * factory/bunos/components.json), .git-blame-ignore-revs (mass-format commits found in history) and the
 * `.gitmodules` keys `shallow = true` / `update = none`. All are deterministic and idempotent.
 */
import { resolve } from "node:path";
import { git, gitlinks, loadProfiles } from "./git-scale.ts";

const BEGIN = "# >>> bunrepo managed (aphrody-bun git generate attributes) >>>";
const END = "# <<< bunrepo managed <<<";

/** Attributes per git docs (gitattributes: text/eol/diff/binary; linguist-* are GitHub Linguist overrides). */
export const ATTRIBUTES = [
  "# Lockfiles and generated manifests: no textual diff in `git diff`, collapsed in GitHub reviews.",
  "bun.lock text eol=lf -diff linguist-generated",
  "Cargo.lock text eol=lf -diff linguist-generated",
  "sources.lock.json text eol=lf linguist-generated",
  "factory/bunos/components.json text eol=lf linguist-generated",
  "*.lockb binary linguist-generated",
  "# Third-party trees are not repository code.",
  "vendor/** linguist-vendored",
  "docs/** linguist-documentation",
  "# Binary assets: never normalise line endings or diff as text.",
  "*.png binary",
  "*.jpg binary",
  "*.jpeg binary",
  "*.gif binary",
  "*.webp binary",
  "*.ico binary",
  "*.woff binary",
  "*.woff2 binary",
  "*.ttf binary",
  "*.otf binary",
  "*.tgz binary",
  "*.zip binary",
  "*.wasm binary",
  "*.node binary",
];

export function upsertBlock(text: string, block: string[], begin = BEGIN, end = END) {
  const body = [begin, ...block, end].join("\n");
  const re = new RegExp(`${begin.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${end.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`);
  const norm = text.replace(/\r\n/g, "\n");
  return re.test(norm) ? norm.replace(re, body) : `${norm.replace(/\n*$/, "\n")}\n${body}\n`;
}

export async function writeAttributes(root: string) {
  const file = resolve(root, ".gitattributes");
  const next = upsertBlock(await Bun.file(file).text(), ATTRIBUTES);
  await Bun.write(file, next);
  return next;
}

export interface Components {
  components: { id: string; path?: string; integration?: { owner?: string } }[];
}

/** Pure: CODEOWNERS text. More specific paths come later (last match wins in CODEOWNERS). */
export function renderCodeowners(manifest: Components, topDirs: string[], gitlinkPaths: string[], defaultOwner: string) {
  const paths = new Set<string>(topDirs.map(d => `/${d}/`));
  const skip = (p: string) => !p || p.includes("$") || p.includes("(") || gitlinkPaths.some(g => p === g || p.startsWith(`${g}/`));
  for (const c of manifest.components)
    for (const raw of (c.path ?? "").split(",")) {
      const p = raw.trim().replace(/\/+$/, "");
      if (!skip(p) && !p.startsWith("sources/") && p.includes("/")) paths.add(`/${p}/`);
    }
  const lines = [...paths].sort((a, b) => a.split("/").length - b.split("/").length || a.localeCompare(b)).map(p => `${p.padEnd(48)} ${defaultOwner}`);
  return [
    "# CODEOWNERS draft generated by `aphrody-bun git generate codeowners` from factory/bunos/components.json.",
    "# Replace the owner of a line by the team that owns the area; last matching pattern wins.",
    "# Submodule (gitlink) paths are omitted: ownership lives in each submodule repository.",
    `* ${defaultOwner}`,
    ...lines,
    "",
  ].join("\n");
}

export async function writeCodeowners(root: string, owner = "@aphrody-dev") {
  const manifest = (await Bun.file(resolve(root, "factory/bunos/components.json")).json()) as Components;
  const top = (await git(root, ["ls-tree", "-d", "--name-only", "HEAD"])).out.split("\n").filter(Boolean);
  const text = renderCodeowners(manifest, top, await gitlinks(root), owner);
  await Bun.write(resolve(root, ".github/CODEOWNERS"), text);
  return text;
}

export const FORMAT_SUBJECT = /\b(format|formatted|fmt|rustfmt|prettier|style|lint|reformat)\b/i;

/** Pure: commits whose subject says formatting and that touch at least `minFiles` files. */
export function pickFormatCommits(log: string, minFiles: number) {
  const out: { sha: string; subject: string; files: number }[] = [];
  let cur: { sha: string; subject: string } | undefined;
  for (const line of log.split("\n")) {
    const h = line.match(/^([0-9a-f]{40})\t(.*)$/);
    if (h) cur = { sha: h[1]!, subject: h[2]! };
    const s = line.match(/(\d+) files? changed/);
    if (s && cur) {
      if (Number(s[1]) >= minFiles && FORMAT_SUBJECT.test(cur.subject)) out.push({ ...cur, files: Number(s[1]) });
      cur = undefined;
    }
  }
  return out;
}

export async function writeIgnoreRevs(root: string, minFiles = 200) {
  const log = await git(root, ["log", "--no-merges", "--shortstat", "--format=%H%x09%s"]);
  const picked = pickFormatCommits(log.out, minFiles).reverse();
  const text = [
    "# Mass-format commits (subject mentions formatting, >= " + minFiles + " files changed), oldest first.",
    "# Used by `git blame --ignore-revs-file .git-blame-ignore-revs`; `aphrody-bun git setup` sets blame.ignoreRevsFile.",
    ...picked.flatMap(c => [`# ${c.subject.slice(0, 100)} (${c.files} files)`, c.sha]),
    "",
  ].join("\n");
  await Bun.write(resolve(root, ".git-blame-ignore-revs"), text);
  return picked;
}

/** `shallow = true` on every non-optional submodule that lacks it, `update = none` on the optional ones. */
export async function writeGitmodulesKeys(root: string) {
  const file = ".gitmodules";
  const { optionalSubmodules } = await loadProfiles();
  const all = (await git(root, ["config", "-f", file, "--list"])).out.split("\n").filter(Boolean);
  const have = new Map(all.map(l => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)] as const));
  const changes: string[] = [];
  for (const [key, path] of have) {
    if (!key.startsWith("submodule.") || !key.endsWith(".path")) continue;
    const name = key.slice("submodule.".length, -".path".length);
    const wants = [["shallow", "true"], ...(optionalSubmodules.includes(path) ? [["update", "none"]] : [])];
    for (const [k, v] of wants) {
      if (have.get(`submodule.${name}.${k}`) === v) continue;
      await git(root, ["config", "-f", file, `submodule.${name}.${k}`, v!]);
      changes.push(`${path}: ${k}=${v}`);
    }
  }
  return changes;
}
