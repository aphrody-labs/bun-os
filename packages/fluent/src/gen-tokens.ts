#!/usr/bin/env bun
// Generates the Fluent 2 skin of Bun OS. The token recipe is Microsoft's (@fluentui/react-theme v9 createLightTheme /
// createDarkTheme); the brand ramp it is fed is the Material 3 primary tonal palette of the product seed, computed by
// the canonical engine (crates/aphrody-m3-tokens through @aphrody/m3-tokens/wasm), so Fluent and M3 surfaces share
// one accent (docs/DESIGN-SYSTEM.md, WinUI 3 adapter).
//   tokens/fluent2.json        all tokens, light and dark, plus the brand ramp and its source
//   tokens/fluent2.css         CSS custom properties (names as in @fluentui/web-components: --colorBrandBackground, ...)
//   tokens/fluent2.toml        flat [light] / [dark] tables for non-web consumers
//   app/FluentTokens.xaml      WinUI 3 ResourceDictionary: colour tokens as SolidColorBrush (Fluent2.<token>)
// `--check` regenerates in memory and fails when a committed output differs.
import { join } from "node:path";
import { brandRamp, PRODUCT_SEED } from "./brand.ts";
import { installFluent, PINS } from "./deps.ts";

type Tokens = Record<string, string | number>;
type ThemeModule = {
  createLightTheme(brand: Record<number, string>): Tokens;
  createDarkTheme(brand: Record<number, string>): Tokens;
};

const dir = await installFluent();
const fluent = (await import(join(dir, "node_modules/@fluentui/react-theme/lib/index.js"))) as ThemeModule;
const brand = brandRamp(PRODUCT_SEED);
const light = fluent.createLightTheme(brand);
const dark = fluent.createDarkTheme(brand);
const root = join(import.meta.dir, "..");
const source = `@fluentui/react-theme@${PINS["@fluentui/react-theme"]} with the M3 primary tonal palette of ${PRODUCT_SEED}`;

const css = (t: Tokens) =>
  Object.entries(t)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");
const toml = (t: Tokens) =>
  Object.entries(t)
    .map(([k, v]) => `${k} = ${typeof v === "number" ? v : JSON.stringify(v)}`)
    .join("\n");
const hex = /^#([0-9a-fA-F]{6})$/;
const brushes = (t: Tokens) =>
  Object.entries(t)
    .filter(([, v]) => typeof v === "string" && hex.test(v))
    .map(([k, v]) => `      <SolidColorBrush x:Key="Fluent2.${k}" Color="${v}"/>`)
    .join("\n");

const outputs: Record<string, string> = {
  "tokens/fluent2.json":
    JSON.stringify({ source: PINS, seed: PRODUCT_SEED, variant: "tonal-spot", brand, light, dark }, null, 1) + "\n",
  "tokens/fluent2.css": `/* Generated by src/gen-tokens.ts from ${source}. Do not edit. */\n:root {\n${css(light)}\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n${css(dark).replace(/^/gm, "  ")}\n  }\n}\n`,
  "tokens/fluent2.toml": `# Generated by src/gen-tokens.ts from ${source}. Do not edit.\n[light]\n${toml(light)}\n\n[dark]\n${toml(dark)}\n`,
  // the WinUI project compiles it from its own directory (a Page outside the project dir breaks the XAML compiler)
  "app/FluentTokens.xaml": `<!-- Generated by src/gen-tokens.ts from ${source}. Do not edit. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <ResourceDictionary.ThemeDictionaries>
    <ResourceDictionary x:Key="Light">
${brushes(light)}
    </ResourceDictionary>
    <ResourceDictionary x:Key="Dark">
${brushes(dark)}
    </ResourceDictionary>
  </ResourceDictionary.ThemeDictionaries>
</ResourceDictionary>
`,
};

if (process.argv.includes("--check")) {
  const stale: string[] = [];
  for (const [path, text] of Object.entries(outputs)) {
    const file = Bun.file(join(root, path));
    if (!(await file.exists()) || (await file.text()) !== text) stale.push(path);
  }
  if (stale.length) throw new Error(`stale generated files (run bun src/gen-tokens.ts): ${stale.join(", ")}`);
  console.log("fluent tokens are current");
} else {
  for (const [path, text] of Object.entries(outputs)) await Bun.write(join(root, path), text);
  console.log(
    `tokens: ${Object.keys(light).length} light, ${Object.keys(dark).length} dark, brand from ${PRODUCT_SEED}`,
  );
}
