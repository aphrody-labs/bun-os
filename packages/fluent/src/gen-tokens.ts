#!/usr/bin/env bun
// Generates the Fluent 2 tokens of Bun OS from the Microsoft source of truth: @fluentui/react-theme (microsoft/fluentui, v9) webLightTheme / webDarkTheme.
//   tokens/fluent2.json   all tokens, light and dark
//   tokens/fluent2.css    CSS custom properties (names as in @fluentui/web-components: --colorBrandBackground, ...)
//   app/FluentTokens.xaml      WinUI 3 ResourceDictionary: colour tokens as SolidColorBrush (Fluent2.<token>), Light and Dark theme dictionaries
import { join } from "node:path";
import { installFluent, PINS } from "./deps.ts";

const dir = await installFluent();
const theme = (await import(join(dir, "node_modules/@fluentui/react-theme/lib/index.js"))) as Record<
  string,
  Record<string, string | number>
>;
const light = theme.webLightTheme!,
  dark = theme.webDarkTheme!;
const out = join(import.meta.dir, "..", "tokens");

const css = (t: Record<string, string | number>) =>
  Object.entries(t)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");
await Bun.write(join(out, "fluent2.json"), JSON.stringify({ source: PINS, light, dark }, null, 1) + "\n");
await Bun.write(
  join(out, "fluent2.css"),
  `/* Generated by src/gen-tokens.ts from @fluentui/react-theme@${PINS["@fluentui/react-theme"]}. Do not edit. */\n:root {\n${css(light)}\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n${css(dark).replace(/^/gm, "  ")}\n  }\n}\n`,
);

// Neutral flat TOML for non-web consumers (Rust/egui craft apps): [light] / [dark] tables, string values keep their CSS units, numbers stay numbers.
const toml = (t: Record<string, string | number>) =>
  Object.entries(t)
    .map(([k, v]) => `${k} = ${typeof v === "number" ? v : JSON.stringify(v)}`)
    .join("\n");
await Bun.write(
  join(out, "fluent2.toml"),
  `# Generated by src/gen-tokens.ts from @fluentui/react-theme@${PINS["@fluentui/react-theme"]}. Do not edit.\n[light]\n${toml(light)}\n\n[dark]\n${toml(dark)}\n`,
);

const hex = /^#([0-9a-fA-F]{6})$/;
const brushes = (t: Record<string, string | number>) =>
  Object.entries(t)
    .filter(([, v]) => typeof v === "string" && hex.test(v))
    .map(([k, v]) => `      <SolidColorBrush x:Key="Fluent2.${k}" Color="${v}"/>`)
    .join("\n");
// the WinUI project compiles it from its own directory (a Page outside the project dir breaks the XAML compiler)
const xamlPath = join(import.meta.dir, "..", "app", "FluentTokens.xaml");
await Bun.write(
  xamlPath,
  `<!-- Generated by src/gen-tokens.ts from @fluentui/react-theme@${PINS["@fluentui/react-theme"]}. Do not edit. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <ResourceDictionary.ThemeDictionaries>
    <ResourceDictionary x:Key="Light">
${brushes(light)}
    </ResourceDictionary>
    <ResourceDictionary x:Key="Dark">
${brushes(dark)}
    </ResourceDictionary>
  </ResourceDictionary.ThemeDictionaries>
</ResourceDictionary>
`,
);
console.log(`tokens: ${Object.keys(light).length} light, ${Object.keys(dark).length} dark`);
