#!/usr/bin/env bun
// Typed projection of Windows.winmd (Windows SDK 10.0.26100.0) to TypeScript declarations:
//   bun packages/microsoft/src/winmd.ts <out.d.ts> <Namespace> [<Namespace>...]
// Reads the metadata with the .NET tool in ../winmd (System.Reflection.Metadata) and maps WinRT types to TypeScript.
import { join } from "node:path";

export interface WinmdType {
  ns: string;
  name: string;
  kind: "class" | "interface" | "enum" | "struct" | "delegate";
  base: string;
  methods: { name: string; returns: string; parameters: { name: string; type: string }[] }[];
  fields: { name: string; type: string; value: unknown }[];
}

const PRIMS: Record<string, string> = {
  Boolean: "boolean",
  Byte: "number",
  SByte: "number",
  Int16: "number",
  UInt16: "number",
  Int32: "number",
  UInt32: "number",
  Int64: "bigint",
  UInt64: "bigint",
  Single: "number",
  Double: "number",
  Char: "string",
  String: "string",
  Void: "void",
  Object: "unknown",
};

const tsType = (t: string): string => {
  const generic = /^([\w.`]+)<(.+)>$/.exec(t);
  if (generic) {
    const base = generic[1]!.replace(/`\d+$/, "");
    if (base === "Windows.Foundation.IAsyncOperation") return `Promise<${tsType(generic[2]!)}>`;
    if (base === "Windows.Foundation.Collections.IVector" || base === "Windows.Foundation.Collections.IVectorView")
      return `${tsType(generic[2]!)}[]`;
    return "unknown";
  }
  if (t.endsWith("[]")) return `${tsType(t.slice(0, -2))}[]`;
  if (t.startsWith("System.")) return PRIMS[t.slice(7)] ?? "unknown";
  if (PRIMS[t]) return PRIMS[t]!;
  return /^[A-Za-z_][\w.]*$/.test(t) ? t : "unknown";
};

export function toDts(types: WinmdType[]): string {
  const byNs = new Map<string, WinmdType[]>();
  for (const t of types) byNs.set(t.ns, [...(byNs.get(t.ns) ?? []), t]);
  const out = [
    "// Generated by packages/microsoft/src/winmd.ts from Windows.winmd (Windows SDK 10.0.26100.0). Do not edit.",
    "",
  ];
  for (const [ns, list] of [...byNs].sort()) {
    out.push(`declare namespace ${ns} {`);
    for (const t of list.sort((a, b) => a.name.localeCompare(b.name))) {
      const name = t.name.replace(/`\d+$/, "");
      if (t.kind === "enum") {
        out.push(`  enum ${name} {`, ...t.fields.map(f => `    ${f.name} = ${f.value},`), "  }");
      } else if (t.kind === "struct") {
        out.push(`  interface ${name} {`, ...t.fields.map(f => `    ${f.name}: ${tsType(f.type)};`), "  }");
      } else if (t.kind === "delegate") {
        out.push(`  type ${name} = (...args: unknown[]) => unknown;`);
      } else {
        const members = t.methods.map(
          m =>
            `    ${m.name}(${m.parameters.map(p => `${/^[A-Za-z_][A-Za-z0-9_]*$/.test(p.name) ? p.name : "arg"}: ${tsType(p.type)}`).join(", ")}): ${tsType(m.returns)};`,
        );
        out.push(`  interface ${name} {`, ...members, "  }");
      }
    }
    out.push("}", "");
  }
  return out.join("\n");
}

export const WINMD = "C:\\Program Files (x86)\\Windows Kits\\10\\UnionMetadata\\10.0.26100.0\\Windows.winmd";

export async function dump(namespaces: string[], winmd = WINMD): Promise<WinmdType[]> {
  const proj = join(import.meta.dir, "..", "winmd", "WinmdDump.csproj");
  const p = Bun.spawn(["dotnet", "run", "-c", "Release", "--project", proj, "--", winmd, ...namespaces], {
    stdout: "pipe",
    stderr: "pipe",
  });
  const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]);
  if (code !== 0) throw new Error(`WinmdDump exited ${code}: ${err || out}`);
  return (JSON.parse(out) as { types: WinmdType[] }).types;
}

if (import.meta.main) {
  const [outFile, ...namespaces] = Bun.argv.slice(2);
  if (!outFile || !namespaces.length) throw new Error("usage: winmd.ts <out.d.ts> <Namespace>...");
  const types = await dump(namespaces);
  await Bun.write(outFile, toDts(types));
  console.log(JSON.stringify({ types: types.length, out: outFile }));
}
