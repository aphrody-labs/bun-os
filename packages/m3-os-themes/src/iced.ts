// Iced GUI toolkit theme emitter (used by libcosmic, egui bridge, and native Bun OS apps).
import { rolesFor, validate } from "./color.ts";
import type { GeneratedFile, Mode, Roles, ThemeInput } from "./types.ts";

/** Converts hex to 0..1 sRGB float string. */
function srgbFloat(hex: string): string {
  const clean = hex.replace("#", "");
  const n = Number.parseInt(clean, 16);
  const r = ((n >> 16) & 255) / 255;
  const g = ((n >> 8) & 255) / 255;
  const b = (n & 255) / 255;
  return `(r: ${r.toFixed(4)}, g: ${g.toFixed(4)}, b: ${b.toFixed(4)})`;
}

/** Generate Iced Palette RON snippet. */
export function icedPaletteRon(roles: Roles, mode: Mode): string {
  const bg = roles["surface"] || (mode === "dark" ? "#111318" : "#f9f9ff");
  const text = roles["onSurface"] || (mode === "dark" ? "#e1e2e9" : "#191c20");
  const primary = roles["primary"] || "#8ab4f8";
  const secondary = roles["secondary"] || "#c2e7ff";
  const tertiary = roles["tertiary"] || "#7cd8e8";
  const success = tertiary;
  const danger = roles["error"] || (mode === "dark" ? "#ffb4ab" : "#ba1a1a");

  return `// Iced Theme Palette (${mode}) - Generated by @aphrody/m3-os-themes.
(
    background: ${srgbFloat(bg)},
    text: ${srgbFloat(text)},
    primary: ${srgbFloat(primary)},
    secondary: ${srgbFloat(secondary)},
    tertiary: ${srgbFloat(tertiary)},
    success: ${srgbFloat(success)},
    danger: ${srgbFloat(danger)},
)
`;
}

/** Pure emitter for Iced target: produces RON palette definitions for light and dark modes. */
export function generateIced(input: ThemeInput): GeneratedFile[] {
  validate(input);
  const out: GeneratedFile[] = [];
  const modes: Mode[] = input.mode === "auto" ? ["light", "dark"] : [input.mode];
  for (const mode of modes) {
    const roles = rolesFor(input, mode).roles;
    out.push({
      target: "iced",
      path: `iced/themes/${input.name}-${mode}.ron`,
      content: icedPaletteRon(roles, mode),
    });
  }
  return out;
}
