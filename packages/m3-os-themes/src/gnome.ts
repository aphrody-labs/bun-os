/** GNOME 47+ `accent-color` names with their reference hues (libadwaita accent set): an upstream enum, not chrome. */
// design:content
const GNOME_ACCENTS: Record<string, string> = {
  blue: "#3584e4",
  teal: "#2190a4",
  green: "#3a944a",
  yellow: "#c88800",
  orange: "#ed5b00",
  red: "#e62d42",
  pink: "#d56199",
  purple: "#9141ac",
  slate: "#6f8396",
};

/** Closest GNOME accent name to a colour (Euclidean RGB distance). */
export function nearestGnomeAccent(color: string): string {
  const c = Number.parseInt(color.slice(1), 16);
  const d = (h: string): number => {
    const n = Number.parseInt(h.slice(1), 16);
    return [16, 8, 0].reduce((s, sh) => s + (((c >> sh) & 255) - ((n >> sh) & 255)) ** 2, 0);
  };
  // eslint-disable-next-line unicorn/no-array-sort -- Sorting fresh entries keeps the shared ES2022 type contract.
  return Object.entries(GNOME_ACCENTS).sort((a, b) => d(a[1]) - d(b[1]))[0]![0];
}

/** libadwaita named colours (also honoured by GTK 3 theme CSS). */
export function adwaitaColors(r: Roles): string {
  const defs: Record<string, string> = {
    accent_color: r["primary"]!,
    accent_bg_color: r["primary"]!,
    accent_fg_color: r["onPrimary"]!,
    destructive_color: r["error"]!,
    destructive_bg_color: r["error"]!,
    destructive_fg_color: r["onError"]!,
    success_color: r["tertiary"]!,
    success_bg_color: r["tertiary"]!,
    success_fg_color: r["onTertiary"]!,
    warning_color: r["secondary"]!,
    warning_bg_color: r["secondaryContainer"]!,
    warning_fg_color: r["onSecondaryContainer"]!,
    error_color: r["error"]!,
    error_bg_color: r["error"]!,
    error_fg_color: r["onError"]!,
    window_bg_color: r["surface"]!,
    window_fg_color: r["onSurface"]!,
    view_bg_color: r["surfaceContainerLowest"]!,
    view_fg_color: r["onSurface"]!,
    headerbar_bg_color: r["surfaceContainer"]!,
    headerbar_fg_color: r["onSurface"]!,
    headerbar_border_color: r["outlineVariant"]!,
    headerbar_backdrop_color: r["surface"]!,
    card_bg_color: r["surfaceContainerLow"]!,
    card_fg_color: r["onSurface"]!,
    dialog_bg_color: r["surfaceContainerHigh"]!,
    dialog_fg_color: r["onSurface"]!,
    popover_bg_color: r["surfaceContainerHigh"]!,
    popover_fg_color: r["onSurface"]!,
    sidebar_bg_color: r["surfaceContainerLow"]!,
    sidebar_fg_color: r["onSurface"]!,
    sidebar_backdrop_color: r["surface"]!,
    sidebar_border_color: r["outlineVariant"]!,
    secondary_sidebar_bg_color: r["surfaceContainer"]!,
    secondary_sidebar_fg_color: r["onSurface"]!,
    thumbnail_bg_color: r["surfaceContainerHighest"]!,
    thumbnail_fg_color: r["onSurface"]!,
    shade_color: `alpha(${r["shadow"]!}, 0.12)`,
    scrollbar_outline_color: r["surface"]!,
  };
  return Object.entries(defs)
    .map(([k, v]) => `@define-color ${k} ${v};`)
    .join("\n");
}

/** The same named colours as GTK 4.16+ / libadwaita 1.6+ CSS variables (`--accent-bg-color`, `--window-bg-color`...). */
export function adwaitaVars(r: Roles): string {
  const body = [...adwaitaColors(r).matchAll(/@define-color (\w+) ([^;]+);/g)]
    .map(m => `  --${m[1]!.replaceAll("_", "-")}: ${m[2]};`)
    .join("\n");
  return `:root {\n${body}\n}`;
}

export function gtkCss(r: Roles, version: 3 | 4): string {
  const extra =
    version === 3
      ? `
@define-color theme_bg_color ${r["surface"]};
@define-color theme_fg_color ${r["onSurface"]};
@define-color theme_base_color ${r["surfaceContainerLowest"]};
@define-color theme_text_color ${r["onSurface"]};
@define-color theme_selected_bg_color ${r["primary"]};
@define-color theme_selected_fg_color ${r["onPrimary"]};
@define-color borders ${r["outlineVariant"]};
`
      : "";
  return `/* Generated by @aphrody/m3-os-themes (m3-os-themes marker) */
${adwaitaColors(r)}
${version === 4 ? adwaitaVars(r) : ""}
${extra}
button.suggested-action, .suggested-action { background-color: ${r["primary"]}; color: ${r["onPrimary"]}; }
button.destructive-action, .destructive-action { background-color: ${r["error"]}; color: ${r["onError"]}; }
switch:checked { background-color: ${r["primary"]}; }
switch:checked slider { background-color: ${r["onPrimary"]}; }
selection, *:selected { background-color: ${r["secondaryContainer"]}; color: ${r["onSecondaryContainer"]}; }
`;
}

