export interface FontFile {
  /** Path inside the google/fonts fork (vendor/fonts) or the Material Symbols fork. */
  source: "google-fonts" | "material-symbols";
  path: string;
  /** Installed file name (Windows %SystemRoot%\Fonts, /usr/share/fonts/bunos-m3/). */
  file: string;
  family: string;
  /** Windows `HKLM\...\Fonts` value name. */
  registry: string;
  license: "OFL-1.1" | "Apache-2.0";
  role: "brand" | "plain" | "serif" | "code" | "mono" | "coverage" | "emoji" | "icons";
}

const gf = (
  dir: string,
  src: string,
  file: string,
  family: string,
  role: FontFile["role"],
  italic = false,
): FontFile => ({
  source: "google-fonts",
  path: `ofl/${dir}/${src}`,
  file,
  family,
  registry: `${family}${italic ? " Italic" : ""} (TrueType)`,
  license: "OFL-1.1",
  role,
});

