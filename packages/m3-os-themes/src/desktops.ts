/** /etc/fonts/conf.d rule: M3 families as the sans/serif/monospace/emoji defaults, Noto for coverage. */
export function fontconfigConf(): string {
  const prefer = (generic: string, families: string[]) =>
    `  <alias binding="same">\n    <family>${generic}</family>\n    <prefer>\n${families.map(f => `      <family>${f}</family>`).join("\n")}\n    </prefer>\n  </alias>`;
  return `<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Bun OS M3 type defaults: generated by @aphrody/m3-os-themes design. Install as /etc/fonts/conf.d/60-bunos-m3.conf. -->
<fontconfig>
  <dir>/usr/share/fonts/bunos-m3</dir>
${prefer("sans-serif", ["Google Sans Flex", "Roboto Flex", "Noto Sans", "Noto Sans JP", "Noto Sans Symbols", "Noto Sans Symbols 2", "Noto Color Emoji"])}
${prefer("serif", ["Roboto Serif", "Noto Serif", "Noto Sans JP", "Noto Color Emoji"])}
${prefer("monospace", ["Google Sans Code", "Roboto Mono", "Noto Sans Mono", "Noto Sans JP", "Noto Color Emoji"])}
${prefer("emoji", ["Noto Color Emoji"])}
${prefer("system-ui", ["Google Sans Flex", "Roboto Flex", "Noto Sans"])}
  <match target="font">
    <test name="family"><string>Google Sans Flex</string></test>
    <edit name="hintstyle" mode="assign"><const>hintslight</const></edit>
    <edit name="rgba" mode="assign"><const>rgb</const></edit>
    <edit name="lcdfilter" mode="assign"><const>lcddefault</const></edit>
  </match>
</fontconfig>
`;
}
