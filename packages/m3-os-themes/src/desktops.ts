// Desktop-side outputs of the design pipeline that are not window chrome: the Omarchy-format palette the Bun OS
// desktop switch reads (factory/desktop/bunos-desktop/bunos-theme.ts: themes/<name>/colors.toml), a nushell colour
// config, the M3 font set (google/fonts fork, vendor/fonts) with its fontconfig rules and Windows registry names.
import type { Roles } from "./types.ts";

/** Omarchy `colors.toml` from the M3 roles: accent, surfaces, selection and a tone-matched 16-colour ANSI set. */
export function omarchyColors(dark: Roles, ansi: Record<string, string>): string {
  const r = (k: string) => dark[k]!;
  const lines: Record<string, string> = {
    accent: r("primary"),
    cursor: r("primary"),
    foreground: r("onSurface"),
    background: r("surface"),
    selection_foreground: r("onPrimaryContainer"),
    selection_background: r("primaryContainer"),
    ...ansi,
  };
  return `# Bun OS M3 palette (Omarchy colors.toml format): generated by @aphrody/m3-os-themes design. Do not hand-edit.\n${Object.entries(
    lines,
  )
    .map(([k, v]) => `${k} = "${v}"`)
    .join("\n")}\n`;
}

