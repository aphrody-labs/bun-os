/** ANSI 0-15 from the dark roles (same mapping as the Rio palette in apps.ts). */
export function ansiFromRoles(
  dark: Roles,
  harmonized: { red: string; green: string; yellow: string },
): Record<string, string> {
  const r = (k: string) => dark[k]!;
  return {
    color0: r("surfaceContainerHigh"),
    color1: harmonized.red,
    color2: harmonized.green,
    color3: harmonized.yellow,
    color4: r("primary"),
    color5: r("tertiary"),
    color6: r("secondary"),
    color7: r("onSurfaceVariant"),
    color8: r("outline"),
    color9: r("onErrorContainer"),
    color10: harmonized.green,
    color11: harmonized.yellow,
    color12: r("onPrimaryContainer"),
    color13: r("onTertiaryContainer"),
    color14: r("onSecondaryContainer"),
    color15: r("onSurface"),
  };
}

/** nushell `$env.config.color_config` (source it from config.nu). */
export function nushellTheme(dark: Roles, ansi: Record<string, string>): string {
  const r = (k: string) => dark[k]!;
  const map: Record<string, string> = {
    separator: r("outline"),
    leading_trailing_space_bg: r("surfaceContainerHigh"),
    header: `{ fg: "${r("primary")}" attr: b }`,
    empty: r("outline"),
    bool: ansi["color6"]!,
    int: ansi["color5"]!,
    float: ansi["color5"]!,
    filesize: ansi["color4"]!,
    duration: ansi["color3"]!,
    date: ansi["color13"]!,
    range: ansi["color3"]!,
    string: ansi["color2"]!,
    nothing: r("outline"),
    binary: ansi["color5"]!,
    cell_path: r("onSurfaceVariant"),
    row_index: `{ fg: "${r("secondary")}" attr: b }`,
    record: r("onSurface"),
    list: r("onSurface"),
    block: r("onSurface"),
    hints: r("outline"),
    search_result: `{ fg: "${r("onPrimary")}" bg: "${r("primary")}" }`,
    shape_garbage: `{ fg: "${r("onError")}" bg: "${r("error")}" attr: b }`,
    shape_external: ansi["color6"]!,
    shape_externalarg: ansi["color2"]!,
    shape_internalcall: `{ fg: "${r("primary")}" attr: b }`,
    shape_string: ansi["color2"]!,
    shape_int: ansi["color5"]!,
    shape_flag: `{ fg: "${r("tertiary")}" attr: b }`,
    shape_variable: r("secondary"),
    shape_pipe: r("primary"),
    shape_operator: r("tertiary"),
    shape_filepath: ansi["color6"]!,
    shape_globpattern: ansi["color6"]!,
  };
  const body = Object.entries(map)
    .map(([k, v]) => `    ${k}: ${v.startsWith("{") ? v : `"${v}"`}`)
    .join("\n");
  return `# Bun OS M3 nushell theme: generated by @aphrody/m3-os-themes design. Do not hand-edit.\n# Use: source bunos-m3.nu (from config.nu).\n$env.config.color_config = {\n${body}\n}\n`;
}

