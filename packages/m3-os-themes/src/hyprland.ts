/** Generate Fuzzel app launcher INI config. */
export function fuzzelIni(roles: Roles, _mode: Mode): string {
  const bg = roles["surfaceContainer"]!.replace("#", "") + "f2";
  const text = roles["onSurface"]!.replace("#", "") + "ff";
  const match = roles["primary"]!.replace("#", "") + "ff";
  const selBg = roles["primaryContainer"]!.replace("#", "") + "ff";
  const selText = roles["onPrimaryContainer"]!.replace("#", "") + "ff";
  const border = roles["outline"]!.replace("#", "") + "88";

  return `[main]
font=Google Sans:size=12,Inter:size=12
dpi-aware=yes
prompt="Search apps, files, or ask Gemini: "
icon-theme=Papirus
icons-enabled=yes
fields=name,generic,comment,categories,keywords
lines=8
width=36
horizontal-pad=24
vertical-pad=16
inner-pad=12
image-size-ratio=0.5

[colors]
background=${bg}
text=${text}
match=${match}
selection=${selBg}
selection-text=${selText}
selection-match=${match}
border=${border}

[border]
width=2
radius=24
`;
}

/** Pure emitter for Hyprland target: produces hyprland.conf snippet, waybar.css, and fuzzel.ini. */
export function generateHyprland(input: ThemeInput): GeneratedFile[] {
  validate(input);
  const out: GeneratedFile[] = [];

  const modes: Mode[] = input.mode === "auto" ? ["light", "dark"] : [input.mode];
  for (const mode of modes) {
    const roles = rolesFor(input, mode).roles;
    out.push(
      {
        target: "hyprland",
        path: `hypr/themes/${input.name}-${mode}.conf`,
        content: hyprlandColors(roles, mode),
      },
      {
        target: "hyprland",
        path: `waybar/themes/${input.name}-${mode}.css`,
        content: waybarCss(roles, mode),
      },
      {
        target: "hyprland",
        path: `fuzzel/themes/${input.name}-${mode}.ini`,
        content: fuzzelIni(roles, mode),
      },
    );
  }

  return out;
}
