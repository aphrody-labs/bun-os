// Hyprland Wayland compositor + Waybar + Fuzzel launcher theme emitter.
// Maps M3 colour roles and Aluminium OS tokens directly into Hyprland config syntax.
import { rolesFor, validate } from "./color.ts";
import type { GeneratedFile, Mode, Roles, ThemeInput } from "./types.ts";

/** Convert hex '#rrggbb' to Hyprland rgba format: 'rgba(rrggbbaa)'. */
export function hyprRgba(hex: string, alpha = "ff"): string {
  const clean = hex.replace("#", "").toLowerCase();
  return `rgba(${clean}${alpha})`;
}

/** Generate hyprland.conf theme colors snippet. */
export function hyprlandColors(roles: Roles, mode: Mode): string {
  const activeBorder1 = hyprRgba(roles["primary"]!, "ff");
  const activeBorder2 = hyprRgba(roles["secondary"] || roles["tertiary"]!, "cc");
  const inactiveBorder = hyprRgba(roles["outlineVariant"] || roles["surfaceContainerHighest"]!, "88");
  const shadowColor = hyprRgba(roles["shadow"] || "#000000", mode === "dark" ? "77" : "33");

  return `# Material 3 Expressive / Bun OS Hyprland Theme (${mode})
# Generated by @aphrody/m3-os-themes. Do not hand-edit.

general {
    gaps_in = 6
    gaps_out = 12
    border_size = 2
    col.active_border = ${activeBorder1} ${activeBorder2} 45deg
    col.inactive_border = ${inactiveBorder}
    layout = dwindle
}

decoration {
    rounding = 14
    active_opacity = 1.0
    inactive_opacity = 0.94
    
    blur {
        enabled = true
        size = 8
        passes = 3
        new_optimizations = true
        xray = false
        noise = 0.02
        contrast = 0.95
        brightness = 0.95
    }

    shadow {
        enabled = true
        range = 24
        render_power = 3
        color = ${shadowColor}
    }
}

# Floating ChromiumOS / Android 17 Shelf & Gemini Glow Bar window rules
windowrulev2 = float,class:^(com.aphrody.glowbar)$
windowrulev2 = pin,class:^(com.aphrody.glowbar)$
windowrulev2 = noborder,class:^(com.aphrody.glowbar)$
windowrulev2 = nodim,class:^(com.aphrody.glowbar)$
windowrulev2 = noshadow,class:^(com.aphrody.glowbar)$
windowrulev2 = float,class:^(com.google.android.apps.*)$
windowrulev2 = rounding 20,class:^(com.google.android.apps.*)$
`;
}

