// Writes svgs/macos_close.svg, svgs/macos_minimize.svg and svgs/macos_fullscreen.svg from the Bun OS window
// chrome spec: @aphrody/m3-os-themes `trafficLightSvg` over the product ThemeExport (dark mode, glyphs shown, as
// a static icon cannot switch on hover). The colours come from the Rust ThemeExport; nothing is hand-picked.
//
//   bun run gen:traffic-lights            # rewrite the three files
//   bun run gen:traffic-lights -- --check # fail when a committed file is stale

import { join } from "node:path";
import { BUNOS_THEME } from "@aphrody/m3-os-themes";
// chrome.ts is not part of the package exports yet; the spec and its artwork are its only owner.
import { chromeSpec, trafficLightSvg } from "../../m3-os-themes/src/chrome.ts";

const FILES = { close: "macos_close.svg", minimize: "macos_minimize.svg", zoom: "macos_fullscreen.svg" } as const;
const HEADER =
  "<!-- GENERATED by packages/assets/scripts/traffic-lights.ts from @aphrody/m3-os-themes trafficLightSvg (product ThemeExport, dark). Do not hand-edit. -->";

const spec = chromeSpec(BUNOS_THEME);
const check = process.argv.includes("--check");
const stale: string[] = [];
for (const [button, file] of Object.entries(FILES) as [keyof typeof FILES, string][]) {
  const path = join(import.meta.dir, "..", "svgs", file);
  const content = `${HEADER}\n${trafficLightSvg(spec.dark, button, "hover")}\n`;
  if (check) {
    const current = await Bun.file(path)
      .text()
      .catch(() => "");
    if (current !== content) stale.push(file);
  } else await Bun.write(path, content);
}
if (stale.length) {
  console.error(`stale traffic-light svgs: ${stale.join(", ")} (run bun run gen:traffic-lights)`);
  process.exit(1);
}
