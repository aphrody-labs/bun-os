/**
 * Upstream catalogue: every upstream that Aphrody reads but does not need on disk.
 *
 *   list [--tier build|reference]  catalogue with the local state of each entry
 *   drift                          observed commit vs the remote head (git ls-remote), no checkout
 *   refresh [--apply]              record the remote heads as `observedCommit` in tools/config/upstream-sources.json
 *   fetch <id> [--path <p>...]     shallow, blob-less clone into the disposable cache (sparse with --path); prints the path
 *   prune [--apply] [--cache]      remove checkouts under the source root that are not vital (clean ones only);
 *                                  --cache also empties the fetch cache
 *   docs [--apply]                 regenerate docs/reference/infra/UPSTREAMS.md from the manifest
 *
 * Live reads without any clone: `aphrody git upstream list|info|tree|read|search <id>` and the `upstream_*` MCP tools.
 */
import { existsSync, readdirSync, rmSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "../process.ts";
import { Ctx } from "../context.ts";
import { refHead } from "./drift.ts";
import { lsRemote } from "../deps/inventory.ts";
import { parseManifest, resolveSourceRoot, type Manifest, type Reference } from "./restore.ts";

const MANIFEST = "tools/config/upstream-sources.json";
export const DOC = "docs/reference/infra/UPSTREAMS.md";

const git = (args: string[], cwd?: string) =>
  spawnSync("git", args, {
    cwd,
    encoding: "utf8",
    timeout: 600_000,
    env: { ...process.env, GIT_TERMINAL_PROMPT: "0" },
  });

export function cacheRoot(): string {
  return join(process.env.XDG_CACHE_HOME ?? join(homedir(), ".cache"), "aphrody", "upstream");
}

export function loadManifest(c: Ctx): Manifest {
  return parseManifest(c.read(MANIFEST));
}

export function findReference(manifest: Manifest, id: string): Reference | undefined {
  return (manifest.reference ?? []).find(r => r.id === id);
}

/** `owner/name` of a GitHub URL, when it is one. */
export function githubSlug(url: string): string | undefined {
  return /^https:\/\/github\.com\/([^/]+\/[^/]+?)(?:\.git)?\/?$/.exec(url)?.[1];
}

/** Clean means: no changed paths and no commit that the remote does not have. */
function isClean(dir: string): { clean: boolean; why?: string } {
  if (!existsSync(join(dir, ".git"))) return { clean: false, why: "not a git checkout" };
  const status = git(["status", "--porcelain"], dir);
  if (status.stdout.trim())
    return {
      clean: false,
      why: `${status.stdout.trim().split("\n").length} changed paths`,
    };
  const ahead = git(["log", "--oneline", "--branches", "--not", "--remotes"], dir);
  if (ahead.status === 0 && ahead.stdout.trim()) return { clean: false, why: "unpushed commits" };
  return { clean: true };
}

/** Directories of the source root that are neither vital sources nor a `*.pre-bump-*` leftover handled by `sources prune`. */
export function nonVital(root: string, manifest: Manifest): string[] {
  if (!existsSync(root)) return [];
  const vital = new Set(manifest.sources.map(s => s.id));
  return readdirSync(root, { withFileTypes: true })
    .filter(e => e.isDirectory() && !vital.has(e.name) && !e.name.includes(".pre-bump-"))
    .map(e => e.name)
    .toSorted();
}

export type ForkEntry = {
  repo: string;
  role?: string;
  parent?: string;
  keep?: string;
};

export function renderDocs(manifest: Manifest, forks: ForkEntry[] = []): string {
  const rows = (tier: string) =>
    (manifest.reference ?? [])
      .filter(r => r.tier === tier)
      .map(r => {
        const slug = githubSlug(r.url);
        const link = slug ? `[${slug}](${r.url.replace(/\.git$/, "")})` : r.url;
        return `| \`${r.id}\` | ${link} | \`${r.ref ?? "HEAD"}\` | ${r.observedCommit?.slice(0, 10) ?? "-"} | ${r.purpose}${r.note ? ` ${r.note}` : ""} | ${r.consumers} |`;
      });
  const vital = manifest.sources.map(s => {
    const origin = s.kind === "crate" ? `crates.io \`${s.crate}\` ${s.version}` : `${s.url} \`${s.ref ?? "HEAD"}\``;
    const why = s.cargoPathDep !== undefined ? "Cargo path dependency" : "build input";
    const patches = (s.patches ?? []).map(p => `\`${p.file}\``).join(", ") || "-";
    return `| \`${s.id}\` | ${origin} | ${why}${s.hold ? ` (held: ${s.hold})` : ""} | ${patches} |`;
  });
  return `<!-- SPDX-License-Identifier: Apache-2.0 -->
<!-- Generated by \`yolo update upstream docs --apply\` from tools/config/upstream-sources.json. Do not edit by hand. -->
# Upstreams

Patched Rust implementations are tracked inside the Aphrody Cargo workspace. Only optional build inputs live under the source root
(\`${manifest.root}\` (not in repo), an untracked machine-local cache; override with \`APHRODY_SOURCE_ROOT\`); everything else is a catalogue entry that is read live.

## Integrated Rust implementations (${manifest.integrated?.length ?? 0})

Source, tests and licences are tracked in the monorepo; Cargo needs no sibling checkout.

| Package | Version | Owner path | Preserved patches |
| --- | --- | --- | --- |
${(manifest.integrated ?? []).map(s => `| \`${s.crate}\` | ${s.version} | \`${s.integratedPath}\` | ${(s.patches ?? []).map(p => `\`${p.file}\``).join(", ")} |`).join("\n")}

## Vital checkouts (${manifest.sources.length})

Restored by \`bun run sources:sync\` (or \`aphrody git source sync --apply\`); each is a Cargo path dependency with local patches.

| Id | Origin | Why it stays | Patches |
| --- | --- | --- | --- |
${vital.join("\n")}

## Reference upstreams (${(manifest.reference ?? []).filter(r => r.tier === "reference").length}, never cloned by default)

| Id | Repository | Ref | Observed | What it is for | Used by |
| --- | --- | --- | --- | --- | --- |
${rows("reference").join("\n")}

## Build-on-demand upstreams (${(manifest.reference ?? []).filter(r => r.tier === "build").length})

Inputs of the WSL build (\`tools/config/os/wsl-build.json\`, \`crates/infra/aphrody-command/src/wsl\`). Restore one with
\`yolo update sources sync --only <id> --apply\` before a WSL build; remove it afterwards with
\`yolo update upstream prune --apply\`.

| Id | Repository | Ref | Observed | What it is for | Used by |
| --- | --- | --- | --- | --- | --- |
${rows("build").join("\n")}

## Forks (${forks.length})

Every fork needs a reason to exist; \`yolo update sources forks\` compares each with its parent.

| Fork | Parent | Role | Why it stays |
| --- | --- | --- | --- |
${forks.map(f => `| \`${f.repo}\` | ${f.parent ?? "-"} | ${f.role ?? "-"} | ${f.keep ?? "undocumented"} |`).join("\n")}

## Access

| Need | Command |
| --- | --- |
| Catalogue | \`aphrody git upstream list\`, MCP \`upstream_list\`, \`yolo update upstream list\` |
| Live repository facts (head, latest release, pushed date, licence, archived) | \`aphrody git upstream info <id>\`, MCP \`upstream_info\` |
| Directory listing at the live head | \`aphrody git upstream tree <id> [path]\`, MCP \`upstream_tree\` |
| One file at the live head | \`aphrody git upstream read <id> <path>\`, MCP \`upstream_read\` |
| Code search inside one upstream | \`aphrody git upstream search <id> <query>\`, MCP \`upstream_search\` |
| Full local read (shallow clone in \`~/.cache/aphrody/upstream\`) | \`yolo update upstream fetch <id> [--path <dir>]\` |
| Drift of the observed heads | \`yolo update upstream drift\`; record them with \`upstream refresh --apply\` |
| Agent entry point | skill \`upstreams\` (\`~/plugins/aphrody/skills/upstreams\`) |

The Cargo git dependencies (oxc-project/oxc, hf-hub) are tracked by \`yolo update sources drift\`;
forks by \`yolo update sources forks\`. The Bun fork the former Bun fork is the Bun of Aphrody (its own repository, merged with upstream by its scripts/aphrody/sync-upstream.ts); the Oxc fork was retired on 2026-10-02.
`;
}

export async function runUpstream(c: Ctx, args: string[]): Promise<number> {
  const [sub = "list", ...rest] = args;
  const manifest = loadManifest(c);
  const refs = manifest.reference ?? [];
  const root = resolveSourceRoot(c.root, manifest, undefined);
  switch (sub) {
    case "list": {
      const ti = rest.indexOf("--tier");
      const tier = ti >= 0 ? rest[ti + 1] : undefined;
      for (const r of refs.filter(x => !tier || x.tier === tier)) {
        const local = existsSync(join(root, r.id)) ? "local" : "remote";
        console.log(
          `${r.tier.padEnd(9)} ${local.padEnd(6)} ${r.id.padEnd(24)} ${r.url
            .replace("https://github.com/", "")
            .replace(/\.git$/, "")
            .padEnd(34)} ${r.purpose}`,
        );
      }
      const extra = nonVital(root, manifest);
      if (extra.length) console.log(`not vital on disk: ${extra.join(", ")}  (yolo update upstream prune --apply)`);
      return 0;
    }
    case "drift": {
      let moved = 0;
      for (const r of refs) {
        const head = refHead(r.url, r.ref ?? "HEAD");
        const tag = lsRemote(r.url).latestTag;
        const behind = !!head && !!r.observedCommit && head !== r.observedCommit;
        moved += behind ? 1 : 0;
        console.log(
          `${behind ? "moved" : head ? "same " : "?    "} ${r.id.padEnd(24)} ${(r.observedCommit ?? "-").slice(0, 10)} -> ${(head ?? "unreachable").slice(0, 10)}${tag ? `  tag ${tag}` : ""}`,
        );
      }
      console.log(`upstream  ${moved} reference(s) moved since observed`);
      return 0;
    }
    case "refresh": {
      const next = structuredClone(manifest);
      let changed = 0;
      for (const r of next.reference ?? []) {
        const head = refHead(r.url, r.ref ?? "HEAD");
        if (head && head !== r.observedCommit) {
          console.log(
            `${c.apply ? "update" : "would update"} ${r.id} ${(r.observedCommit ?? "-").slice(0, 10)} -> ${head.slice(0, 10)}`,
          );
          r.observedCommit = head;
          changed++;
        }
      }
      if (c.apply && changed) c.write(MANIFEST, `${JSON.stringify(next, null, 2)}\n`);
      if (!changed) console.log("refresh  observed commits already current");
      return 0;
    }
    case "fetch": {
      const id = rest[0];
      const r = id ? findReference(manifest, id) : undefined;
      if (!r) return (console.error(`usage: upstream fetch <id>; ids: ${refs.map(x => x.id).join(", ")}`), 2);
      const paths: string[] = [];
      for (let i = 1; i < rest.length; i++) if (rest[i] === "--path" && rest[i + 1]) paths.push(rest[++i]!);
      const sparse = paths.length ? paths : (r.sparse ?? []);
      const dir = join(cacheRoot(), r.id);
      if (existsSync(dir)) {
        const pulled = git(["fetch", "--depth", "1", "--quiet", "origin", r.ref ?? "HEAD"], dir);
        if (pulled.status !== 0) return (console.error(`fetch failed: ${pulled.stderr.trim()}`), 1);
        git(["checkout", "--quiet", "--detach", "FETCH_HEAD"], dir);
      } else {
        const clone = git([
          "clone",
          "--quiet",
          "--depth",
          "1",
          "--filter=blob:none",
          ...(sparse.length ? ["--sparse"] : []),
          ...(r.ref ? ["--branch", r.ref] : []),
          r.url,
          dir,
        ]);
        if (clone.status !== 0) return (console.error(`clone failed: ${clone.stderr.trim()}`), 1);
      }
      if (sparse.length) git(["sparse-checkout", "set", "--cone", ...sparse], dir);
      console.log(dir);
      return 0;
    }
    case "prune": {
      let skipped = 0;
      for (const id of nonVital(root, manifest)) {
        const dir = join(root, id);
        const state = isClean(dir);
        if (!state.clean) {
          skipped++;
          console.log(`keep   ${dir} (${state.why})`);
          continue;
        }
        console.log(`${c.apply ? "remove" : "would remove"} ${dir}`);
        if (c.apply) rmSync(dir, { recursive: true, force: true });
      }
      if (rest.includes("--cache") && existsSync(cacheRoot())) {
        console.log(`${c.apply ? "remove" : "would remove"} ${cacheRoot()}`);
        if (c.apply) rmSync(cacheRoot(), { recursive: true, force: true });
      }
      if (!c.apply) console.log("plan only; pass --apply to remove");
      return skipped ? 1 : 0;
    }
    case "docs": {
      const text = renderDocs(
        manifest,
        c.jsonFile<{ forks: ForkEntry[] }>("tools/config/update/forks.json", {
          forks: [],
        }).forks,
      );
      if (c.apply) {
        c.write(DOC, text);
        console.log(`wrote ${DOC}`);
        return 0;
      }
      const current = c.exists(DOC) ? c.read(DOC) : "";
      if (current === text) {
        console.log(`docs   ${DOC} current`);
        return 0;
      }
      console.log(`docs   ${DOC} is stale; run \`yolo update upstream docs --apply\``);
      return 1;
    }
    default:
      console.error("usage: upstream [list|drift|refresh|fetch <id>|prune [--cache]|docs] [--apply]");
      return 2;
  }
}
