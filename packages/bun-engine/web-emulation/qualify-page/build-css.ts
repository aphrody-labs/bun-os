// Writes emulator.css: the generated Aphrody brand roles (packages/app-ui/src/brand.css, product seed, light
// and dark) followed by emulator.src.css. The page is served as four static files (qualify-webos.ts and the
// WebOS emulators router), so the sheet is inlined here instead of imported. `--check` fails when stale.
import { join } from "node:path";

const here = import.meta.dir;
const brand = join(here, "..", "..", "..", "app-ui", "src", "brand.css");
const target = join(here, "emulator.css");

export async function emulatorCss(): Promise<string> {
  const [roles, page] = await Promise.all([Bun.file(brand).text(), Bun.file(join(here, "emulator.src.css")).text()]);
  return `/* emulator.css, generated by packages/bun-engine/web-emulation/qualify-page/build-css.ts from
   packages/app-ui/src/brand.css and emulator.src.css. Do not hand-edit: run bun build-css.ts. */
${roles.trimEnd()}

${page}`;
}

if (import.meta.main) {
  const css = await emulatorCss();
  if (process.argv.includes("--check")) {
    const current = await Bun.file(target).text().catch(() => "");
    if (current !== css) {
      console.error("emulator.css is stale: run bun packages/bun-engine/web-emulation/qualify-page/build-css.ts");
      process.exit(1);
    }
  } else {
    await Bun.write(target, css);
    console.log(`wrote ${target}`);
  }
}
