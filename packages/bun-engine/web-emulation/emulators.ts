export type QualificationStatus = "pass" | "fail" | "untested" | "unsupported";

export interface QualificationEntry {
  id: string;
  status: QualificationStatus;
  testedAt?: string;
  frames?: number;
  lit?: boolean;
  hash?: string;
  audio?: string;
  renderer?: string;
  saveState?: "ok" | "unsupported" | "fail";
  errors: string[];
  detail?: string;
  screenshot?: string;
  fixture?: { file: string; sha256: string; license: string; source: string };
  /** URL the test ran against (the WebOS origin). */
  url?: string;
}

export interface QualificationReport {
  schemaVersion: 1;
  generatedAt: string;
  base: string;
  sourceCommit?: string;
  entries: Record<string, QualificationEntry>;
}
