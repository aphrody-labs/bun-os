// Writes _assets_/styles.css, the stylesheet every scaffolded app receives: @aphrody/m3-theme/tokens.css (the
// generated M3 roles, light and dark by prefers-color-scheme) followed by _assets_/styles.src.css. The templates are
// embedded in the CLI binary and several of them (Trunk, Dioxus) have no npm resolution, so the sheet is copied here.
// Run: bun build-styles.ts (or --check to fail when styles.css is stale).
import { join } from "node:path";

const assets = join(import.meta.dir, "_assets_");
const tokens = join(import.meta.dir, "..", "..", "..", "..", "m3-theme", "tokens.css");
const target = join(assets, "styles.css");

export async function scaffoldStyles(): Promise<string> {
  const [sheet, page] = await Promise.all([Bun.file(tokens).text(), Bun.file(join(assets, "styles.src.css")).text()]);
  return `/* Scaffold stylesheet, generated by aphrody-create-tauri-app/templates/build-styles.ts from
   @aphrody/m3-theme/tokens.css and _assets_/styles.src.css. Do not hand-edit: run bun build-styles.ts. */
${sheet.trimEnd()}

${page}`;
}

if (import.meta.main) {
  const css = await scaffoldStyles();
  if (process.argv.includes("--check")) {
    if ((await Bun.file(target).text()) !== css) {
      console.error("templates/_assets_/styles.css is stale: run bun build-styles.ts");
      process.exit(1);
    }
  } else {
    await Bun.write(target, css);
    console.log(`wrote ${target}`);
  }
}
