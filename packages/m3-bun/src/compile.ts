// `m3-bun compile`: one executable that serves the UI and the API. The UI is built first (`buildApp`), then a
// generated entry embeds every build file (`import ... with { type: "file" }`), the API module and the
// runtime (`runApp`), and `Bun.build({ compile })` links them with the Bun runtime. Cross targets download the
// matching Bun runtime on first use.
//
// Bytecode: the app is compiled with `bytecode: true` (JavaScriptCore bytecode embedded next to the source), which
// skips parsing at start-up: on the fixture app `--version` takes 4.3 ms instead of 7.5 ms and the first /healthz
// 5.8 ms instead of 9.3 ms (medians, same host); the executable grows by about 1.5 MB. Bytecode output is CommonJS, so
// the generated entry has no top-level await. `compile.bytecode: false` in the app config turns it off.
//
// Limit, measured: the executable is the Bun runtime plus the app. It is not static. The glibc targets need
// libc, libm, libdl, libpthread and the loader at run time; the `-musl` targets need musl and libstdc++. A
// container or distro image therefore carries those libraries (see `rootfs` in package.ts and the `docker`
// target) instead of being empty.
import { existsSync } from "node:fs";
import { mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { buildApp, minifyOptions, readManifest, type BuildReport, type MinifyLevel } from "./build.ts";
import { compileTarget, loadApp, type CompileTargetName, type M3App } from "./config.ts";

export interface EntryParams {
  /** Absolute path of `entry.ts` of this package. */
  runtime: string;
  /** Absolute path of the API module, if any. */
  api?: string;
  /** `[url path, absolute file path]` of every embedded file. */
  files: ReadonlyArray<readonly [string, string]>;
  name: string;
  version: string;
  buildId: string;
  port: number;
  csp?: string | false;
}

/** The source of the generated entry module. Pure, so tests read it. */
export function renderEntry(params: EntryParams): string {
  const imports = params.files.map(
    ([, file], i) => `import file${i} from ${JSON.stringify(file)} with { type: "file" };`,
  );
  const table = params.files.map(([url], i) => `  ${JSON.stringify(url)}: file${i},`);
  return [
    "// Generated by @aphrody/m3-bun compile. Do not edit.",
    `import { runApp } from ${JSON.stringify(params.runtime)};`,
    ...(params.api ? [`import api from ${JSON.stringify(params.api)};`] : []),
    ...imports,
    "",
    // No top-level await: bytecode compilation emits CommonJS, which has none.
    "runApp({",
    `  name: ${JSON.stringify(params.name)},`,
    `  version: ${JSON.stringify(params.version)},`,
    `  buildId: ${JSON.stringify(params.buildId)},`,
    `  port: ${params.port},`,
    ...(params.csp !== undefined ? [`  csp: ${JSON.stringify(params.csp)},`] : []),
    ...(params.api ? ["  api,"] : []),
    "  files: {",
    ...table,
    "  },",
    "}).catch((error: unknown) => {",
    "  console.error(error);",
    "  process.exit(1);",
    "});",
    "",
  ].join("\n");
}

/** Default output path of the executable of `app` for `target`. */
export function defaultOutfile(app: M3App, target: CompileTargetName | undefined): string {
  const configured = app.bun.compile?.outfile;
  const suffix = (target ?? "").startsWith("windows") || (!target && process.platform === "win32") ? ".exe" : "";
  if (configured) return resolve(app.dir, configured.endsWith(suffix) ? configured : `${configured}${suffix}`);
  return join(app.dir, "bin", `${app.name}${target ? `-${target}` : ""}${suffix}`);
}

export interface CompileOptions {
  dir?: string;
  configFile?: string;
  /** Friendly target name (`linux-x64-musl`, `windows-x64`, ...). Default: the host. */
  target?: CompileTargetName;
  outfile?: string;
  minify?: MinifyLevel;
  /** Build the UI first (default true); false uses the existing build directory. */
  build?: boolean;
  app?: M3App;
}

export interface CompileReport {
  app: M3App;
  target: string;
  outfile: string;
  bytes: number;
  ms: number;
  entryFile: string;
  build?: BuildReport;
  files: number;
  /** Things that did not apply as configured (for example Windows metadata when not compiling on Windows). */
  warnings: string[];
  /** The app was compiled with embedded JavaScriptCore bytecode (faster start). */
  bytecode: boolean;
}

/** Compile the app into one executable. */
export async function compileApp(options: CompileOptions = {}): Promise<CompileReport> {
  const started = performance.now();
  const app = options.app ?? (await loadApp(resolve(options.dir ?? process.cwd()), options.configFile));
  const target = options.target ?? app.bun.compile?.target;
  const minify = options.minify ?? app.minify;

  let build: BuildReport | undefined;
  if (options.build !== false) build = await buildApp({ app, minify });
  const manifest = build?.manifest ?? readManifest(app.outdir);
  if (!manifest) throw new Error(`m3-bun: no build in ${app.outdir}; run m3-bun build or compile without --no-build`);

  const files = manifest.files.map(f => [`/${f.path}`, join(app.outdir, f.path)] as const);
  const entryFile = join(app.dir, "node_modules", ".cache", "m3-bun", "server.ts");
  await mkdir(dirname(entryFile), { recursive: true });
  await Bun.write(
    entryFile,
    renderEntry({
      runtime: join(import.meta.dir, "entry.ts"),
      ...(app.api ? { api: app.api } : {}),
      files,
      name: app.name,
      version: app.version,
      buildId: manifest.buildId,
      port: app.port,
      ...(app.bun.csp !== undefined ? { csp: app.bun.csp } : {}),
    }),
  );

  const outfile = resolve(options.outfile ?? defaultOutfile(app, target));
  await mkdir(dirname(outfile), { recursive: true });
  // Bun applies Windows executable metadata (icon, title, publisher, ...) only when it runs on Windows; elsewhere the
  // flags are refused on the command line and silently ignored by Bun.build, so say so instead of pretending.
  const warnings: string[] = [];
  const wantsWindows = (target ?? "").startsWith("windows");
  const configuredWindows = app.bun.compile?.windows;
  const windows = wantsWindows && process.platform === "win32" ? configuredWindows : undefined;
  if (wantsWindows && configuredWindows && process.platform !== "win32") {
    warnings.push(
      "compile.windows metadata (icon, title, publisher, version) is only applied when compiling on Windows; this executable has none (build-windows.ps1 applies it on a Windows host)",
    );
  }
  const compileTargetString = compileTarget(target);
  const bytecode = app.bun.compile?.bytecode !== false;
  const result = await Bun.build({
    entrypoints: [entryFile],
    compile: {
      outfile,
      ...(compileTargetString ? { target: compileTargetString } : {}),
      autoloadDotenv: false,
      autoloadBunfig: false,
      ...(windows
        ? {
            windows: {
              ...windows,
              ...(windows.icon ? { icon: resolve(app.dir, windows.icon) } : {}),
            },
          }
        : {}),
    },
    minify: minifyOptions(minify),
    sourcemap: "none",
    ...(bytecode ? { bytecode: true } : {}),
    define: { "process.env.NODE_ENV": '"production"' },
    throw: false,
  });
  if (!result.success) throw new Error(`m3-bun: compile failed:\n${result.logs.map(String).join("\n")}`);
  if (!existsSync(outfile)) throw new Error(`m3-bun: compile reported success but wrote no ${outfile}`);
  return {
    app,
    target: compileTargetString ?? `host (${process.platform}-${process.arch})`,
    outfile,
    bytes: Bun.file(outfile).size,
    ms: Math.round(performance.now() - started),
    entryFile,
    ...(build ? { build } : {}),
    files: files.length,
    warnings,
    bytecode,
  };
}
