#!/usr/bin/env bun
// Bun OS fleet tool. Reads infra/fleet/fleet.toml and derives SSH access, host firewalls and audits from it.
// Usage: bun infra/fleet/fleet.ts <ssh-config|firewall <host>|apply-firewall <host>|audit [host]|hosts>
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { homedir, platform } from "node:os";
import fleetToml from "./fleet.toml";

type Host = {
  description: string;
  aliases?: string[];
  provider?: string;
  os: string;
  roles: string[];
  user?: string;
  mesh_ip: string;
  public_ipv4?: string;
  public_ipv6?: string;
  public_interface?: string;
  cpus?: number;
  memory_gib?: number;
  host_key: string;
  checkout?: string;
  public_tcp?: number[];
  public_udp?: number[];
  managed?: boolean;
  ssh?: boolean;
};

type Fleet = {
  schema: number;
  mesh: { name: string; interface: string; cidr: string; hub: string; keepalive: number };
  ssh: {
    identity: string;
    known_hosts: string;
    server_alive_interval: number;
    server_alive_count_max: number;
    connect_timeout: number;
    control_persist: string;
  };
  hosts: Record<string, Host>;
};

const fleet = fleetToml as unknown as Fleet;
const here = import.meta.dir;
const generated = join(here, "generated");
const managed = Object.entries(fleet.hosts).filter(([, h]) => h.managed !== false);

function die(message: string): never {
  console.error(`fleet: ${message}`);
  process.exit(2);
}

function host(name: string | undefined): [string, Host] {
  if (!name) die("missing host name");
  const found = Object.entries(fleet.hosts).find(([n, h]) => n === name || h.aliases?.includes(name));
  if (!found) die(`unknown host ${name}; known: ${Object.keys(fleet.hosts).join(", ")}`);
  return found;
}

// ---------------------------------------------------------------------------------------------------------------------
// SSH client configuration
// ---------------------------------------------------------------------------------------------------------------------

// The generated config is installed into ~/.ssh/fleet/ and included as `Include fleet/ssh_config`, a path every
// OpenSSH build (Windows, MSYS, Linux) resolves relative to ~/.ssh.
function sshConfig(variant: "windows" | "unix"): string {
  const s = fleet.ssh;
  const lines = [
    "# Generated by `bun infra/fleet/fleet.ts ssh-config` from infra/fleet/fleet.toml. Do not edit.",
    "# Installed as ~/.ssh/fleet/ssh_config; ~/.ssh/config starts with `Include fleet/ssh_config`.",
    "",
  ];
  const common = (name: string, h: Host, address: string) => {
    lines.push(`    HostName ${address}`);
    if (h.user) lines.push(`    User ${h.user}`);
    lines.push(
      `    HostKeyAlias ${name}`,
      `    IdentityFile ${s.identity}`,
      "    IdentitiesOnly yes",
      "    UserKnownHostsFile ~/.ssh/fleet/known_hosts",
      "    StrictHostKeyChecking yes",
      "    BatchMode yes",
      `    ConnectTimeout ${s.connect_timeout}`,
      `    ServerAliveInterval ${s.server_alive_interval}`,
      `    ServerAliveCountMax ${s.server_alive_count_max}`,
    );
    // Windows OpenSSH has no Unix-socket multiplexing; ControlMaster there fails with "getsockname failed".
    if (variant === "unix") {
      lines.push("    ControlMaster auto", "    ControlPath ~/.ssh/cm-%C", `    ControlPersist ${s.control_persist}`);
    }
  };
  for (const [name, h] of Object.entries(fleet.hosts)) {
    if (h.ssh === false) continue;
    lines.push(`# ${h.description}`, `Host ${[name, ...(h.aliases ?? [])].join(" ")}`);
    common(name, h, h.mesh_ip);
    lines.push("");
    if (h.managed !== false) {
      lines.push(`Host ${name}-t`);
      common(name, h, h.mesh_ip);
      lines.push("    BatchMode no", "    RequestTTY yes", "    RemoteCommand tmux new-session -A -s main", "");
    }
    if (h.public_ipv4) {
      lines.push("# Recovery path when the mesh is down", `Host ${name}-public`);
      common(name, h, h.public_ipv4);
      lines.push("");
    }
  }
  return lines.join("\n");
}

function knownHosts(): string {
  const lines = ["# Generated from infra/fleet/fleet.toml. Pinned host keys, keyed by HostKeyAlias."];
  for (const [name, h] of Object.entries(fleet.hosts)) {
    if (h.ssh === false) continue;
    lines.push(`${[name, ...(h.aliases ?? [])].join(",")} ${h.host_key}`);
  }
  return `${lines.join("\n")}\n`;
}

async function writeSshConfig(install: boolean): Promise<void> {
  await mkdir(generated, { recursive: true });
  await Bun.write(join(generated, "ssh_config.windows"), sshConfig("windows"));
  await Bun.write(join(generated, "ssh_config.unix"), sshConfig("unix"));
  await Bun.write(join(generated, "known_hosts"), knownHosts());
  console.log(`wrote ${join(generated, "{ssh_config.windows,ssh_config.unix,known_hosts}")}`);
  if (!install) return;
  const dotSsh = join(homedir(), ".ssh");
  await mkdir(join(dotSsh, "fleet"), { recursive: true });
  await Bun.write(join(dotSsh, "fleet", "ssh_config"), sshConfig(platform() === "win32" ? "windows" : "unix"));
  await Bun.write(join(dotSsh, "fleet", "known_hosts"), knownHosts());
  const userConfig = join(dotSsh, "config");
  const current = (await Bun.file(userConfig).exists()) ? await Bun.file(userConfig).text() : "";
  const kept = current
    .split("\n")
    .filter(l => !/^Include\s+.*fleet\/(generated\/)?ssh_config/.test(l))
    .join("\n")
    .replace(/^\n+/, "");
  await Bun.write(userConfig, `Include fleet/ssh_config\n\n${kept}`);
  console.log(`installed ${join(dotSsh, "fleet")} and the Include line in ${userConfig}`);
}

// ---------------------------------------------------------------------------------------------------------------------
// Firewall (nftables, table inet fleet; coexists with Docker's iptables-nft tables)
// ---------------------------------------------------------------------------------------------------------------------

function firewall(name: string, h: Host): string {
  if (!h.public_interface) die(`${name} has no public_interface`);
  const peers4 = managed.map(([, p]) => p.public_ipv4).filter(Boolean);
  const peers6 = managed.map(([, p]) => p.public_ipv6).filter(Boolean);
  const set = (xs: (string | number | undefined)[]) => `{ ${xs.join(", ")} }`;
  return `#!/usr/sbin/nft -f
# Generated by \`bun infra/fleet/fleet.ts firewall ${name}\` from infra/fleet/fleet.toml. Do not edit on the host.
# Only the public interface (${h.public_interface}) is filtered; mesh, loopback and container bridges are trusted.
table inet fleet
delete table inet fleet
table inet fleet {
  chain input {
    type filter hook input priority filter - 10; policy accept;
    iifname != "${h.public_interface}" accept
    ct state established,related accept
    ct state invalid drop
    meta l4proto { icmp, ipv6-icmp } accept
    ip saddr ${set(peers4)} accept
    ip6 saddr ${set(peers6)} accept
${h.public_tcp?.length ? `    tcp dport ${set(h.public_tcp)} accept\n` : ""}${h.public_udp?.length ? `    udp dport ${set(h.public_udp)} accept\n` : ""}    counter drop
  }
}
`;
}

const firewallUnit = `[Unit]
Description=Bun OS fleet host firewall (nftables table inet fleet)
Documentation=file:///etc/fleet/firewall.nft
Wants=network-pre.target
Before=network-pre.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStartPre=-/sbin/modprobe -a nf_conntrack nft_ct
ExecStart=/usr/bin/nft -f /etc/fleet/firewall.nft
ExecStop=/usr/bin/nft delete table inet fleet

[Install]
WantedBy=multi-user.target
`;

// The mesh hub routes peer-to-peer mesh traffic (wg1 -> wg1). Docker sets the iptables FORWARD policy to DROP, and an
// nftables accept cannot override another base chain's drop, so the allowance goes into DOCKER-USER (Docker's
// documented hook for host rules), once Docker has created it.
const meshForwardUnit = (iface: string) => `[Unit]
Description=Bun OS fleet mesh forwarding on the hub (${iface} -> ${iface})
After=docker.service fleet-firewall.service
Wants=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/bin/sh -c 'iptables -C DOCKER-USER -i ${iface} -o ${iface} -j ACCEPT 2>/dev/null || iptables -I DOCKER-USER -i ${iface} -o ${iface} -j ACCEPT'
ExecStop=-/bin/sh -c 'iptables -D DOCKER-USER -i ${iface} -o ${iface} -j ACCEPT'

[Install]
WantedBy=multi-user.target
`;

async function ssh(
  name: string,
  script: string,
  opts: { quiet?: boolean } = {},
): Promise<{ code: number; out: string }> {
  const proc = Bun.spawn(["ssh", name, "bash -s"], { stdin: "pipe", stdout: "pipe", stderr: "pipe" });
  // Parse the whole script before running it: commands such as sudo-rs read stdin and would swallow the rest.
  proc.stdin.write(`fleet_main() {\n${script}\n}\nfleet_main </dev/null\n`);
  await proc.stdin.end();
  const [out, err] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text()]);
  const code = await proc.exited;
  if (!opts.quiet && err.trim()) console.error(err.trim());
  return { code, out };
}

async function applyFirewall(name: string, h: Host): Promise<void> {
  const rules = firewall(name, h);
  const sudo = h.user === "root" ? "" : "sudo -n ";
  const guard = "fleet-firewall-rollback";
  const hub = name === fleet.mesh.hub;
  // 1. Install and load the ruleset behind a dead-man switch that removes it after 180 s.
  const stage = await ssh(
    name,
    `set -euo pipefail
${sudo}install -d -m 0755 /etc/fleet
${sudo}tee /etc/fleet/firewall.nft >/dev/null <<'NFT'
${rules}NFT
${sudo}tee /etc/systemd/system/fleet-firewall.service >/dev/null <<'UNIT'
${firewallUnit}UNIT
${sudo}modprobe -a nf_conntrack nft_ct
${sudo}nft -c -f /etc/fleet/firewall.nft
${sudo}systemctl stop ${guard}.timer 2>/dev/null || true
${sudo}sed -i "s#/usr/bin/nft#$(command -v nft)#g" /etc/systemd/system/fleet-firewall.service
${sudo}systemd-run --unit=${guard} --on-active=180 "$(command -v nft)" delete table inet fleet >/dev/null
${sudo}nft -f /etc/fleet/firewall.nft
${
  hub
    ? `${sudo}tee /etc/systemd/system/fleet-mesh-forward.service >/dev/null <<'UNIT'
${meshForwardUnit(fleet.mesh.interface)}UNIT
`
    : ""
}echo staged
`,
  );
  if (stage.code !== 0 || !stage.out.includes("staged")) die(`staging the firewall on ${name} failed`);
  // 2. Prove a fresh session still works (new TCP connection, so no multiplexed channel can hide a lockout).
  const probe = Bun.spawn(["ssh", "-o", "ControlMaster=no", "-o", "ControlPath=none", name, "echo alive"], {
    stdout: "pipe",
    stderr: "pipe",
  });
  const alive = (await new Response(probe.stdout).text()).includes("alive") && (await probe.exited) === 0;
  if (!alive) die(`fresh SSH session to ${name} failed; the dead-man switch removes the ruleset within 180 s`);
  // 3. Commit: cancel the dead-man switch and enable the unit for boot.
  const commit = await ssh(
    name,
    `set -euo pipefail
${sudo}systemctl stop ${guard}.timer
${sudo}systemctl daemon-reload
${sudo}systemctl enable fleet-firewall.service >/dev/null 2>&1
${sudo}systemctl start fleet-firewall.service
${
  hub
    ? `${sudo}systemctl enable --now fleet-mesh-forward.service >/dev/null 2>&1
`
    : ""
}echo committed`,
  );
  if (!commit.out.includes("committed")) die(`commit on ${name} failed`);
  console.log(`${name}: firewall applied and enabled`);
}

// ---------------------------------------------------------------------------------------------------------------------
// Audit (read-only)
// ---------------------------------------------------------------------------------------------------------------------

const auditScript = `S=""; [ "$(id -u)" = 0 ] || S="sudo -n"
. /etc/os-release; echo "os=$ID\${VERSION_ID:+-$VERSION_ID}"
echo "cpus=$(nproc)"
echo "mem_gib=$(awk '/MemTotal/{printf "%d", $2/1048576+0.5}' /proc/meminfo)"
echo "mesh=$(ip -4 -o addr | awk '/10\\.200\\.77\\./{print $4}' | cut -d/ -f1 | head -1)"
echo "fleet_fw=$($S nft list table inet fleet >/dev/null 2>&1 && echo on || echo off)"
echo "ufw=$($S ufw status 2>/dev/null | head -1 | awk '{print $2}')"
echo "wg=$(ip -o link show type wireguard | awk -F': ' '{print $2}' | tr '\\n' ' ')"
echo "public_listen=$($S ss -ltnH | awk '{print $4}' | grep -vE '^(127\\.|\\[::1\\]|10\\.|172\\.|192\\.168\\.|\\[fe80|\\[fc|\\[fd)' | sed -E 's/.*://' | sort -un | tr '\\n' ' ')"
echo "root_login=$($S sshd -T 2>/dev/null | awk '/^permitrootlogin/{print $2}')"
echo "password_auth=$($S sshd -T 2>/dev/null | awk '/^passwordauthentication/{print $2}')"
echo "failed_units=$(systemctl --failed --no-legend --plain | awk '{print $1}' | tr '\\n' ' ')"
echo "disk_root=$(df --output=pcent / | tail -1 | tr -d ' ')"
`;

async function audit(names: string[]): Promise<number> {
  let problems = 0;
  for (const [name, h] of managed.filter(([n]) => names.length === 0 || names.includes(n))) {
    const { code, out } = await ssh(name, auditScript, { quiet: true });
    if (code !== 0) {
      console.log(`${name}: UNREACHABLE over the mesh (try ${name}-public)`);
      problems++;
      continue;
    }
    const facts = Object.fromEntries(
      out
        .trim()
        .split("\n")
        .map(l => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim()]),
    );
    const issues: string[] = [];
    if (!facts.os?.startsWith(h.os.split("-")[0])) issues.push(`os ${facts.os} != ${h.os}`);
    if (facts.mesh !== h.mesh_ip) issues.push(`mesh ${facts.mesh} != ${h.mesh_ip}`);
    if (facts.fleet_fw !== "on") issues.push("fleet firewall not loaded");
    if (facts.ufw === "active") issues.push("legacy ufw still active");
    if (/\bwg0\b/.test(facts.wg ?? "")) issues.push("legacy wg0 tunnel still up");
    const allowed = new Set((h.public_tcp ?? []).map(String));
    const extra = (facts.public_listen ?? "").split(" ").filter(p => p && !allowed.has(p));
    if (extra.length) issues.push(`listening publicly beyond public_tcp (filtered if firewall on): ${extra.join(",")}`);
    if (facts.password_auth && facts.password_auth !== "no") issues.push("ssh password authentication enabled");
    if (facts.failed_units) issues.push(`failed units: ${facts.failed_units}`);
    console.log(`${name}: ${facts.os} ${facts.cpus}c ${facts.mem_gib}GiB disk ${facts.disk_root} wg[${facts.wg}]`);
    for (const i of issues) console.log(`  - ${i}`);
    problems += issues.length;
  }
  return problems;
}

// ---------------------------------------------------------------------------------------------------------------------

const [cmd, arg] = process.argv.slice(2);
switch (cmd) {
  case "ssh-config":
    await writeSshConfig(arg !== "--no-install");
    break;
  case "firewall": {
    const [name, h] = host(arg);
    process.stdout.write(firewall(name, h));
    break;
  }
  case "apply-firewall": {
    const [name, h] = host(arg);
    await applyFirewall(name, h);
    break;
  }
  case "audit":
    process.exitCode = (await audit(arg ? [host(arg)[0]] : [])) > 0 ? 1 : 0;
    break;
  case "hosts":
    for (const [name, h] of Object.entries(fleet.hosts)) {
      console.log(`${name.padEnd(12)} ${h.mesh_ip.padEnd(13)} ${h.roles.join(",").padEnd(48)} ${h.description}`);
    }
    break;
  default:
    console.log(
      "usage: bun infra/fleet/fleet.ts <hosts | ssh-config | firewall <host> | apply-firewall <host> | audit [host]>",
    );
    process.exitCode = cmd ? 2 : 0;
}

