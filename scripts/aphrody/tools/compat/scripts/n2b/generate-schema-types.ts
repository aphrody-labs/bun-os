// Generates the Yolo runtime SDK TypeScript types of the canonical n2b report schema
// (crates/contracts/schema/v2.json) into packages/engine/runtime/src/tooling-schema.ts via
// `json-schema-to-typescript --unreachableDefinitions`. The Rust types are generated in
// the former Bun fork packages/bun-n2b (scripts/generate-schema-types.ts) and published as aphrody-n2b-types.
//
// Usage:
//   bun scripts/tools/compat/scripts/n2b/generate-schema-types.ts           # regenerate
//   bun scripts/tools/compat/scripts/n2b/generate-schema-types.ts --check   # exit 1 on drift

import { $ } from "bun";
import { join, resolve } from "node:path";

// scripts/tools/compat/scripts/n2b -> repository root is five levels up.
const REPO_ROOT = resolve(import.meta.dir, "..", "..", "..", "..", "..");

export async function schemaPaths(root = REPO_ROOT) {
  const schema = join(root, "crates/contracts/schema/v2.json");
  if (!(await Bun.file(schema).exists())) {
    throw new Error(`Canonical N2B schema missing: ${schema}`);
  }
  return {
    schema,
    ts: join(root, "packages/engine/runtime/src/tooling-schema.ts"),
  };
}

type SchemaPaths = Awaited<ReturnType<typeof schemaPaths>>;

const BANNER_TS = `// @generated — DO NOT EDIT MANUALLY.
// Regenerate with: bun scripts/tools/compat/scripts/n2b/generate-schema-types.ts
// Source of truth: crates/contracts/schema/v2.json

`;

const HEADER_TS_REGEX =
  /^\/\* eslint-disable \*\/\n\/\*\*\n \* This file was automatically generated by json-schema-to-typescript\.\n \* DO NOT MODIFY IT BY HAND\. Instead, modify the source JSONSchema file,\n \* and run json-schema-to-typescript to regenerate this file\.\n \*\/\n/;

export async function generateTs(paths: SchemaPaths): Promise<string> {
  const result = await $`json2ts --unreachableDefinitions < ${Bun.file(paths.schema)}`.quiet();
  if (result.exitCode !== 0) {
    throw new Error(`json-schema-to-typescript failed: ${result.stderr.toString()}`);
  }
  const out = result.stdout.toString();
  if (!HEADER_TS_REGEX.test(out)) {
    throw new Error("json-schema-to-typescript output header changed; update HEADER_TS_REGEX");
  }
  return BANNER_TS + out.replace(HEADER_TS_REGEX, "").replace(/^\n+/, "");
}

async function main(): Promise<void> {
  const paths = await schemaPaths();
  const ts = await generateTs(paths);
  if (process.argv.includes("--check")) {
    if (ts !== (await Bun.file(paths.ts).text())) {
      console.error(`drift: ${paths.ts}`);
      console.error(
        "\nRun `bun scripts/tools/compat/scripts/n2b/generate-schema-types.ts` and commit the regenerated file.",
      );
      process.exit(1);
    }
    console.log("n2b:codegen:check OK — no drift");
    return;
  }
  await Bun.write(paths.ts, ts);
  console.log(`wrote ${paths.ts}`);
}

if (import.meta.main)
  main().catch(err => {
    console.error(err);
    process.exit(1);
  });
