// ---- meta package ---------------------------------------------------------------------------------------------
const CORE = [
  "shell", "ls", "find", "grep", "cat", "cd", "prompt", "editor", "multiplexer", "file-manager", "disk-usage",
  "process-viewer", "diff", "benchmark", "archiver", "http-client", "fields", "json", "vcs", "git-tui", "task-runner",
  "fuzzy-finder", "help", "watcher", "code-stats", "hexdump", "substitute", "python-tooling", "python-lint",
];
const own = new Set(["coreutils", "findutils", "diffutils", "util-linux", "privilege"]);
const depends = new Set<string>(["bunos-uutils-multicall", "bunos-sudo-rs", "bunos-nushell-default"]);
const optdepends: string[] = [];
const picks: any[] = [];
for (const d of catalog.domains) {
  const c = d.candidates.find((x: any) => x.repo === d.pick);
  if (!c) continue;
  const off = c.arch.official;
  picks.push({
    domain: d.id, status: d.status, repo: c.repo, tag: c.release?.tag ?? null, sha: c.release?.sha ?? null,
    date: c.release?.date ?? null, license: c.license, arch: off ? { repo: off.repo, name: off.pkgname, version: off.version } : null,
  });
  if (own.has(d.id) || !off) continue;
  if (CORE.includes(d.id)) depends.add(off.pkgname);
  else optdepends.push(`${off.pkgname}: ${d.title}`);
}
files.set(
  "pkg/bunos-rust-base/PKGBUILD",
  `# SPDX-License-Identifier: MIT
# Generated by factory/rustbase/gen.ts from catalog.json (ranks are data, see docs/RUSTBASE.md).
# depends = Rust CLI picks that exist in the official Arch repos and are in the CORE set of gen.ts;
# optdepends = the other official-repo picks (desktop, runtimes, services). AUR-only or unpackaged picks are listed in picks.json only.
pkgname=bunos-rust-base
pkgver=${catalog.observedAt.replaceAll("-", ".")}
pkgrel=1
pkgdesc="Bun OS Rust userland meta package: uutils, sudo-rs, nushell and the top-ranked Rust CLIs per domain"
arch=(any)
url="https://github.com/aphrody-labs/bun-os"
license=(MIT)
depends=(${[...depends].sort().join(" ")})
optdepends=(
${optdepends.sort().map(o => "  '" + o + "'").join("\n")}
)
source=(picks.json)
sha256sums=(SKIP)

package() {
  install -Dm644 "$srcdir/picks.json" "$pkgdir/usr/share/bunos/rustbase/picks.json"
}
`,
);
files.set("pkg/bunos-rust-base/picks.json", JSON.stringify({ observedAt: catalog.observedAt, picks }, null, 2) + "\n");

let stale = 0;
for (const [rel, text] of files) {
  const p = join(dir, rel);
  const cur = (await Bun.file(p).exists()) ? await Bun.file(p).text() : null;
  if (cur === text) continue;
  stale++;
  if (checkOnly) console.error(`stale: ${rel}`);
  else await Bun.write(p, text);
}
console.log(`gen: ${files.size} files, ${stale} ${checkOnly ? "stale" : "written"}`);
process.exit(checkOnly && stale ? 1 : 0);
