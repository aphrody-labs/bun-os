#!/usr/bin/env bun
/**
 * Pins and PKGBUILD renderer of the Rust userland.
 *   bun factory/rustbase/gen.ts --refresh   re-read catalog.json + GitHub + Arch API, rewrite pins.json, render
 *   bun factory/rustbase/gen.ts             render pkg/<name>/PKGBUILD (+ derived files) from pins.json
 *   bun factory/rustbase/gen.ts --check     exit 1 if a rendered file differs from disk (no write)
 * Nothing in pkg/ is hand-edited for pins: tags, commits and versions come from pins.json, which comes from catalog.json.
 */
import { join } from "node:path";

const dir = import.meta.dir;
const checkOnly = process.argv.includes("--check");
const refresh = process.argv.includes("--refresh");
const read = (p: string) => Bun.file(join(dir, p)).json();

async function api(url: string, headers: Record<string, string> = {}) {
  const res = await fetch(url, { headers: { "user-agent": "bunos-rustbase", ...headers } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

if (refresh) {
  const catalog = await read("catalog.json");
  const pickOf = (id: string) => {
    const d = catalog.domains.find((x: any) => x.id === id);
    const c = d.candidates.find((x: any) => x.repo === d.pick);
    if (!c?.release?.sha) throw new Error(`${id}: pick has no pinned release`);
    return {
      repo: c.repo,
      tag: c.release.tag,
      sha: c.release.sha,
      date: c.release.date,
      version: String(c.release.tag).replace(/^v/, ""),
      license: c.license,
      archOfficial: c.arch.official ? `${c.arch.official.repo}/${c.arch.official.pkgname} ${c.arch.official.version}` : null,
    };
  };
  const token = (await new Response(Bun.spawn(["gh", "auth", "token"], { stdout: "pipe" }).stdout).text()).trim();
  const fork = "aphrody-labs/uutils-util-linux";
  const head = await api(`https://api.github.com/repos/${fork}/commits/main`, { authorization: `Bearer ${token}` }).catch(() =>
    api(`https://api.github.com/repos/${fork}/commits/HEAD`, { authorization: `Bearer ${token}` }),
  );
  const upstreamUL = catalog.domains.find((x: any) => x.id === "util-linux").candidates[0];
  const gnu: Record<string, string> = {};
  for (const n of ["coreutils", "findutils", "diffutils", "util-linux", "sudo"]) {
    const j: any = await api(`https://archlinux.org/packages/search/json/?name=${n}`);
    const r = j.results.find((x: any) => x.arch === "x86_64" || x.arch === "any");
    gnu[n] = r ? `${r.pkgver}-${r.pkgrel}` : "";
  }
  const pins = {
    schemaVersion: 1,
    observedAt: catalog.observedAt,
    source: "catalog.json picks; fork head from the GitHub API; GNU versions from archlinux.org (core)",
    components: {
      coreutils: pickOf("coreutils"),
      findutils: pickOf("findutils"),
      diffutils: pickOf("diffutils"),
      "sudo-rs": pickOf("privilege"),
      nushell: pickOf("shell"),
      "util-linux": {
        repo: fork,
        upstream: upstreamUL.repo,
        upstreamLatestTag: upstreamUL.release?.tag,
        branch: "main",
        sha: head.sha,
        date: String(head.commit.committer.date).slice(0, 10),
        version: "0.0.1",
        license: upstreamUL.license,
      },
    },
    gnuReplaced: gnu,
  };
  await Bun.write(join(dir, "pins.json"), JSON.stringify(pins, null, 2) + "\n");
}

const pins = await read("pins.json");
const catalog = await read("catalog.json");
const C = pins.components;
const gnuVer = (n: string) => String(pins.gnuReplaced[n]).replace(/-\d+$/, "");

const files = new Map<string, string>();

files.set(
  "pkg/bunos-uutils-multicall/PKGBUILD",
  `# SPDX-License-Identifier: MIT
# Generated by factory/rustbase/gen.ts from pins.json; do not edit the pins by hand.
# uutils coreutils ${C.coreutils.tag} (multicall) + findutils ${C.findutils.tag} + diffutils ${C.diffutils.tag}
# replace the GNU packages; the util-linux fork (${C["util-linux"].repo}) is opt-in through bunos-rust-alternatives
# because Arch util-linux owns libmount/libblkid/mount and cannot be removed.
pkgname=bunos-uutils-multicall
pkgver=${C.coreutils.version}
pkgrel=1
pkgdesc="uutils coreutils (multicall), findutils and diffutils replacing GNU; uutils util-linux applets opt-in"
arch=(x86_64 aarch64)
url="https://github.com/uutils/coreutils"
license=(MIT Apache-2.0)
depends=(glibc gcc-libs)
makedepends=(cargo git make)
# GNU versions are the Arch core versions observed on ${pins.observedAt}; uutils targets the matching GNU behaviour.
provides=(coreutils=${gnuVer("coreutils")} findutils=${gnuVer("findutils")} diffutils=${gnuVer("diffutils")} uutils-coreutils=${C.coreutils.version})
conflicts=(coreutils findutils diffutils uutils-coreutils uutils-findutils uutils-diffutils)
replaces=(uutils-coreutils)
options=(!lto !debug)
source=(
  "coreutils::git+https://github.com/uutils/coreutils.git#commit=${C.coreutils.sha}"
  "findutils::git+https://github.com/uutils/findutils.git#commit=${C.findutils.sha}"
  "diffutils::git+https://github.com/uutils/diffutils.git#commit=${C.diffutils.sha}"
  "util-linux::git+https://github.com/${C["util-linux"].repo}.git#commit=${C["util-linux"].sha}"
  bunos-rust-alternatives
)
sha256sums=(SKIP SKIP SKIP SKIP SKIP)
install=bunos-uutils-multicall.install

prepare() {
  local d
  for d in coreutils findutils diffutils util-linux; do
    (cd "$srcdir/$d" && cargo fetch --locked)
  done
}

build() {
  export CARGO_TARGET_DIR="$srcdir/target"
  (cd "$srcdir/coreutils" && make PROFILE=release MULTICALL=y CARGOFLAGS=--locked)
  local d
  for d in findutils diffutils util-linux; do
    (cd "$srcdir/$d" && cargo build --release --locked --target-dir "$srcdir/target-$d")
  done
}

package() {
  # coreutils: /usr/bin/coreutils + one symlink per applet (LN override: symlinks, not hard links)
  (cd "$srcdir/coreutils" && make install PROFILE=release MULTICALL=y CARGOFLAGS=--locked \\
    PREFIX=/usr DESTDIR="$pkgdir" LN='ln -sf')
  install -Dm644 "$srcdir/coreutils/LICENSE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE-coreutils"

  # findutils: find xargs locate updatedb
  local b
  for b in find xargs locate updatedb; do
    install -Dm755 "$srcdir/target-findutils/release/$b" "$pkgdir/usr/bin/$b"
  done
  install -Dm644 "$srcdir/findutils/LICENSE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE-findutils"

  # diffutils: one multicall binary dispatching on argv[0] suffix (cmp, diff). diff3 and sdiff do not exist upstream.
  install -Dm755 "$srcdir/target-diffutils/release/diffutils" "$pkgdir/usr/bin/diffutils"
  ln -s diffutils "$pkgdir/usr/bin/diff"
  ln -s diffutils "$pkgdir/usr/bin/cmp"
  install -Dm644 "$srcdir/diffutils/LICENSE-MIT" "$pkgdir/usr/share/licenses/$pkgname/LICENSE-diffutils-MIT" 2>/dev/null || true
  install -Dm644 "$srcdir/diffutils/LICENSE-APACHE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE-diffutils-APACHE" 2>/dev/null || true

  # util-linux (fork): staged under /usr/lib/bunos/rust, linked into /usr/local/bin by bunos-rust-alternatives
  install -Dm755 "$srcdir/target-util-linux/release/util-linux" "$pkgdir/usr/lib/bunos/rust/util-linux/util-linux"
  install -dm755 "$pkgdir/usr/lib/bunos/rust/bin"
  local a
  for a in $(sed -n '/^feat_common_core/,/^]/p' "$srcdir/util-linux/Cargo.toml" | grep -o '"[a-z0-9_]*"' | tr -d '"'); do
    ln -s ../util-linux/util-linux "$pkgdir/usr/lib/bunos/rust/bin/$a"
  done
  install -Dm644 "$srcdir/util-linux/LICENSE" "$pkgdir/usr/share/licenses/$pkgname/LICENSE-util-linux"

  install -Dm755 "$srcdir/bunos-rust-alternatives" "$pkgdir/usr/bin/bunos-rust-alternatives"
}
`,
);

files.set(
  "pkg/bunos-uutils-multicall/bunos-uutils-multicall.install",
  `post_install() {
  echo ":: uutils coreutils/findutils/diffutils are active (they replace the GNU packages)."
  echo ":: util-linux applets stay GNU until: bunos-rust-alternatives enable util-linux"
}
post_upgrade() { post_install; }
pre_remove() {
  bunos-rust-alternatives disable util-linux >/dev/null 2>&1 || true
}
`,
);

files.set(
  "pkg/bunos-uutils-multicall/bunos-rust-alternatives",
  `#!/bin/sh
# Opt-in activation of the uutils util-linux applets. Arch util-linux owns the /usr/bin paths, so the Rust applets are
# linked into /usr/local/bin (first in the default PATH) and nothing owned by another package is touched.
set -eu
SRC=/usr/lib/bunos/rust/bin
DST=\${BUNOS_ALT_DST:-/usr/local/bin}
cmd=\${1:-status}; group=\${2:-util-linux}
[ "$group" = util-linux ] || { echo "unknown group: $group" >&2; exit 2; }
case "$cmd" in
  enable)
    mkdir -p "$DST"
    for f in "$SRC"/*; do
      a=$(basename "$f")
      if [ -e "$DST/$a" ] && [ ! -L "$DST/$a" ]; then echo "skip $a (exists, not ours)"; continue; fi
      ln -sf "$f" "$DST/$a"
    done ;;
  disable)
    for f in "$SRC"/*; do
      a=$(basename "$f")
      [ "$(readlink "$DST/$a" 2>/dev/null || true)" = "$f" ] && rm -f "$DST/$a"
    done ;;
  status)
    for f in "$SRC"/*; do
      a=$(basename "$f")
      if [ "$(readlink "$DST/$a" 2>/dev/null || true)" = "$f" ]; then echo "$a rust"; else echo "$a gnu"; fi
    done ;;
  *) echo "usage: bunos-rust-alternatives enable|disable|status [util-linux]" >&2; exit 2 ;;
esac
`,
);

