#!/usr/bin/env bun
// SPDX-License-Identifier: Apache-2.0
// Renders the Arch PKGBUILDs of factory/dotnet-linux/pkg from pins.json (single source of versions and hashes).
//   bun factory/dotnet-linux/gen-pkgbuild.ts           write
//   bun factory/dotnet-linux/gen-pkgbuild.ts --check   exit 1 if a PKGBUILD is stale
// Why repackaged upstream tarballs and not extra/dotnet-sdk or an AUR helper: see docs/DOTNET-LINUX.md (Arch carries the
// 10.0.1xx SDK band, one servicing release behind; PowerShell is AUR only). Hashes: SHA-512 (.NET metadata), SHA-256 (pwsh).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const dir = import.meta.dir;
const pins = JSON.parse(readFileSync(join(dir, "pins.json"), "utf8"));
const files = new Map<string, string>();

const ARCHES: Record<string, string> = { x86_64: "x64", aarch64: "arm64" };

function dotnet(name: string, channel: "10.0" | "11.0", stable: boolean) {
  const p = pins.dotnet[channel];
  const pkgver = p.sdk.replaceAll("-", ".");
  const root = stable ? "/usr/share/dotnet" : "/usr/share/dotnet-preview";
  const bin = stable ? "dotnet" : "dotnet-preview";
  const src = Object.entries(ARCHES)
    .map(([a, rid]) => `source_${a}=("dotnet-sdk-\${_sdk}-linux-${rid}.tar.gz::${p.assets[`linux-${rid}`].url.replaceAll(p.sdk, "${_sdk}")}")`)
    .join("\n");
  const sums = Object.entries(ARCHES)
    .map(([a, rid]) => `sha512sums_${a}=('${p.assets[`linux-${rid}`].sha512}')`)
    .join("\n");
  const provides = stable
    ? `provides=("dotnet-sdk=\${_runtime}" "dotnet-runtime=\${_runtime}" "aspnet-runtime=\${_runtime}" "dotnet-host=\${_runtime}" "dotnet-targeting-pack=\${_runtime}" "dotnet-sdk-${channel}=\${_runtime}" "dotnet-runtime-${channel}=\${_runtime}")
conflicts=(dotnet-sdk dotnet-runtime aspnet-runtime dotnet-host dotnet-targeting-pack aspnet-targeting-pack dotnet-sdk-${channel} dotnet-runtime-${channel} dotnet-source-built-artifacts)`
    : `provides=("dotnet-sdk-preview=\${pkgver}")`; // pkgver form: a pre-release version string has no hyphen
  const profile = stable
    ? `
  install -Dm644 /dev/stdin "$pkgdir/etc/profile.d/dotnet.sh" <<'PROFILE'
export DOTNET_ROOT=/usr/share/dotnet
export DOTNET_CLI_TELEMETRY_OPTOUT=1
PROFILE`
    : "";
  files.set(
    `pkg/${name}/PKGBUILD`,
    `# SPDX-License-Identifier: MIT
# Generated by factory/dotnet-linux/gen-pkgbuild.ts from pins.json. Do not edit.
# The official .NET ${channel} SDK tarball (${p.supportPhase}), repackaged without changes. It contains the SDK, the ${stable ? "" : "preview "}runtime and ASP.NET Core.
# Source of versions and SHA-512: ${p.metadata}
pkgname=${name}
_sdk=${p.sdk}
_runtime=${p.runtime}
pkgver=${pkgver}
pkgrel=1
pkgdesc=".NET ${channel} SDK, runtime and ASP.NET Core runtime from the official tarball (SDK ${p.sdk})"
arch=(x86_64 aarch64)
url="https://dot.net"
license=(MIT)
depends=(glibc gcc-libs icu krb5 openssl zlib libunwind)
makedepends=(libarchive)
optdepends=('clang: NativeAOT publish (ILCompiler links with clang)' 'lttng-ust2.12: CoreCLR tracing')
${provides}
options=(!strip !debug)
${src}
${sums}
noextract=("dotnet-sdk-\${_sdk}-linux-x64.tar.gz" "dotnet-sdk-\${_sdk}-linux-arm64.tar.gz")

package() {
  local _rid=x64; [[ $CARCH == aarch64 ]] && _rid=arm64
  install -dm755 "$pkgdir${root}" "$pkgdir/usr/bin"
  bsdtar -xf "$srcdir/dotnet-sdk-\${_sdk}-linux-${"$"}{CARCH/x86_64/x64}.tar.gz" -C "$pkgdir${root}" --no-same-owner
  ln -s ${root}/dotnet "$pkgdir/usr/bin/${bin}"
  install -Dm644 "$pkgdir${root}/LICENSE.txt" "$pkgdir/usr/share/licenses/$pkgname/LICENSE.txt"
  install -Dm644 "$pkgdir${root}/ThirdPartyNotices.txt" "$pkgdir/usr/share/licenses/$pkgname/ThirdPartyNotices.txt"
  rm "$pkgdir${root}/LICENSE.txt" "$pkgdir${root}/ThirdPartyNotices.txt"${profile}
}
`.replace("${CARCH/x86_64/x64}", "${CARCH/x86_64/x64}").replace(/\$\{CARCH\/x86_64\/x64\}/g, "${_rid}"),
  );
}

function powershell(name: string, kind: "stable" | "preview") {
  const p = pins.powershell[kind];
  const target = kind === "stable" ? "7" : "7-preview";
  const bin = kind === "stable" ? "pwsh" : "pwsh-preview";
  const up = (rid: string) => p.assets[`linux-${rid}`].url.replaceAll(p.version, "${_ver}");
  files.set(
    `pkg/${name}/PKGBUILD`,
    `# SPDX-License-Identifier: MIT
# Generated by factory/dotnet-linux/gen-pkgbuild.ts from pins.json. Do not edit.
# PowerShell ${p.version} from the official GitHub release (${p.release}), repackaged without changes.
# SHA-256 from the release asset hashes.sha256 (equal to the GitHub API asset digest).
pkgname=${name}
_ver=${p.version}
pkgver=${p.version.replaceAll("-", "").replace(/\.preview/, "preview")}
pkgrel=1
pkgdesc="PowerShell ${p.version} (official Linux build, self-contained)"
arch=(x86_64 aarch64)
url="https://github.com/PowerShell/PowerShell"
license=(MIT)
depends=(glibc gcc-libs icu krb5 openssl zlib)
makedepends=(libarchive)
optdepends=('lttng-ust2.12: CoreCLR tracing')
provides=("powershell${kind === "preview" ? "-preview" : ""}=\${${kind === "preview" ? "pkgver" : "_ver"}}")
conflicts=(powershell${kind === "preview" ? "-preview" : ""} powershell${kind === "preview" ? "-preview" : ""}-bin)
options=(!strip !debug)
install=${name}.install
source_x86_64=("powershell-\${_ver}-linux-x64.tar.gz::${up("x64")}")
source_aarch64=("powershell-\${_ver}-linux-arm64.tar.gz::${up("arm64")}")
sha256sums_x86_64=('${p.assets["linux-x64"].sha256}')
sha256sums_aarch64=('${p.assets["linux-arm64"].sha256}')
noextract=("powershell-\${_ver}-linux-x64.tar.gz" "powershell-\${_ver}-linux-arm64.tar.gz")

package() {
  local _rid=x64; [[ $CARCH == aarch64 ]] && _rid=arm64
  install -dm755 "$pkgdir/opt/microsoft/powershell/${target}" "$pkgdir/usr/bin"
  bsdtar -xf "$srcdir/powershell-\${_ver}-linux-\${_rid}.tar.gz" -C "$pkgdir/opt/microsoft/powershell/${target}" --no-same-owner
  # the pwsh executable is not executable in the upstream archive
  chmod 755 "$pkgdir/opt/microsoft/powershell/${target}/pwsh"
  ln -s /opt/microsoft/powershell/${target}/pwsh "$pkgdir/usr/bin/${bin}"
  install -Dm644 "$pkgdir/opt/microsoft/powershell/${target}/LICENSE.txt" "$pkgdir/usr/share/licenses/$pkgname/LICENSE.txt"
}
`,
  );
  files.set(
    `pkg/${name}/${name}.install`,
    `post_install() {
  grep -qxF /usr/bin/${bin} /etc/shells || echo /usr/bin/${bin} >>/etc/shells
}
post_upgrade() { post_install; }
pre_remove() {
  sed -i '\\#^/usr/bin/${bin}$#d' /etc/shells
}
`,
  );
}

// the profile has one source of truth (pwsh/); the package directory gets a copy so makepkg can use it as a source
files.set("pkg/bunos-powershell-default/Microsoft.PowerShell_profile.ps1", readFileSync(join(dir, "pwsh", "Microsoft.PowerShell_profile.ps1"), "utf8"));

dotnet("bunos-dotnet-sdk-bin", "10.0", true);
dotnet("bunos-dotnet-sdk-preview-bin", "11.0", false);
powershell("bunos-powershell-bin", "stable");
powershell("bunos-powershell-preview-bin", "preview");

let stale = 0;
const check = Bun.argv.includes("--check");
for (const [rel, text] of files) {
  const path = join(dir, rel);
  const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  if (current === text) continue;
  stale++;
  if (check) console.error(`stale: ${rel}`);
  else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}
console.log(check ? `${stale} stale PKGBUILD file(s)` : `wrote ${stale} of ${files.size} PKGBUILD file(s)`);
process.exit(check && stale ? 1 : 0);
