const SPACING =
  "(space_none: 0, space_xxxs: 4, space_xxs: 8, space_xs: 12, space_s: 16, space_m: 24, space_l: 32, space_xl: 48, space_xxl: 64, space_xxxl: 128)";
const SQUARE = (() => {
  const r = (v: number) => `(${v.toFixed(1)}, ${v.toFixed(1)}, ${v.toFixed(1)}, ${v.toFixed(1)})`;
  return `(radius_0: ${r(0)}, radius_xs: ${r(2)}, radius_s: ${r(2)}, radius_m: ${r(2)}, radius_l: ${r(2)}, radius_xl: ${r(2)})`;
})();

const hex8 = (c: string) => `"${c.replace(/^#/, "#").toUpperCase()}FF"`;
const some = (c: string) => `Some(${hex8(c)})`;

/** Canonical Omarchy key, then its legacy alias, then a derived fallback. */
function pick(colors: Colors, keys: string[], fallback: () => string): string {
  for (const k of keys) if (colors[k] && /^#[0-9a-f]{6}$/i.test(colors[k]!)) return colors[k]!;
  return fallback();
}

export function cosmicRon(name: string, colors: Colors): string {
  const dark = (colors.mode ?? "dark") !== "light";
  const bg = pick(colors, ["background", "bg"], () => (dark ? "#1a1b26" : "#f5f5f5"));
  const fg = pick(colors, ["foreground", "fg"], () => (dark ? "#c0caf5" : "#222222"));
  const accent = pick(colors, ["accent", "blue", "color4"], () => fg);
  const container = pick(colors, ["lighter_background", "lighter_bg"], () => mix(bg, fg, 6));
  const container2 = mix(container, fg, 5);
  const neutral = pick(colors, ["muted", "selection", "color8"], () => mix(bg, fg, 20));
  const green = pick(colors, ["green", "color2"], () => "#8fd694");
  const yellow = pick(colors, ["yellow", "color3"], () => "#f0c674");
  const red = pick(colors, ["red", "color1"], () => "#f28b9b");
  const palette = (dark ? DARK_PALETTE : LIGHT_PALETTE).replace("{{name}}", `omarchy-${name}`);
  return `// SPDX-License-Identifier: MIT
// ${name} for COSMIC: generated by factory/distro/cosmic-themes.ts from Omarchy themes/${name}/colors.toml
// (basecamp/omarchy, MIT). Apply: bunos-theme-set ${name}.
(
    palette: ${palette},
    spacing: ${SPACING},
    corner_radii: ${SQUARE},
    neutral_tint: ${some(neutral)},
    bg_color: ${some(bg)},
    primary_container_bg: ${some(container)},
    secondary_container_bg: ${some(container2)},
    text_tint: ${some(fg)},
    accent: ${some(accent)},
    success: ${some(green)},
    warning: ${some(yellow)},
    destructive: ${some(red)},
    gaps: (10, 10),
    active_hint: 2,
    window_hint: ${some(accent)},
)
`;
}

/** Rio terminal theme ([colors] table, raphamorim/rio docs) from the 16 ANSI colours or their canonical names. */
export function rioTheme(name: string, colors: Colors): string {
  const c = (i: number, names: string[], fb: string) => pick(colors, [`color${i}`, ...names], () => fb);
  const bg = pick(colors, ["background", "bg"], () => "#1a1b26");
  const fg = pick(colors, ["foreground", "fg"], () => "#c0caf5");
  const accent = pick(colors, ["accent", "blue"], () => fg);
  const lines = [
    `# ${name} for Rio: generated by factory/distro/cosmic-themes.ts from Omarchy themes/${name}/colors.toml (MIT).`,
    "[colors]",
    `background = "${bg}"`,
    `foreground = "${fg}"`,
    `cursor = "${pick(colors, ["cursor"], () => accent)}"`,
    `selection-background = "${pick(colors, ["selection_background", "selection"], () => mix(bg, accent, 35))}"`,
    `selection-foreground = "${pick(colors, ["selection_foreground"], () => fg)}"`,
    `tabs = "${bg}"`,
    `tabs-active = "${accent}"`,
    `black = "${c(0, ["darker_background"], mix(bg, "#000000", 30))}"`,
    `red = "${c(1, ["red"], "#f28b9b")}"`,
    `green = "${c(2, ["green"], "#8fd694")}"`,
    `yellow = "${c(3, ["yellow"], "#f0c674")}"`,
    `blue = "${c(4, ["blue"], accent)}"`,
    `magenta = "${c(5, ["magenta"], "#c9a7ff")}"`,
    `cyan = "${c(6, ["cyan"], "#7fd6c6")}"`,
    `white = "${c(7, ["dark_foreground"], fg)}"`,
    `light-black = "${c(8, ["muted"], mix(bg, fg, 35))}"`,
    `light-red = "${c(9, ["bright_red"], "#ff9fae")}"`,
    `light-green = "${c(10, ["bright_green"], "#a8e6ab")}"`,
    `light-yellow = "${c(11, ["bright_yellow"], "#ffd58f")}"`,
    `light-blue = "${c(12, ["bright_blue"], accent)}"`,
    `light-magenta = "${c(13, ["bright_magenta"], "#dcc2ff")}"`,
    `light-cyan = "${c(14, ["bright_cyan"], "#a6f2e2")}"`,
    `light-white = "${c(15, ["bright_foreground"], fg)}"`,
  ];
  return lines.join("\n") + "\n";
}

/** icons.theme can hold several names without separators in some upstream files: keep the first Yaru-* name. */
export function iconTheme(raw: string | undefined): string {
  const m = raw?.trim().match(/^(Yaru-[a-z]+?(?:-dark)?)(?=Yaru-|$)/i) ?? raw?.trim().match(/^[^\s]+/);
  return m?.[1] ?? m?.[0] ?? "Cosmic";
}

async function main() {
  const { values } = parseArgs({
    options: {
      themes: { type: "string", multiple: true },
      out: { type: "string" },
      backgrounds: { type: "boolean", default: false },
    },
  });
  if (!values.themes?.length || !values.out) throw new Error("--themes DIR... --out DIR [--backgrounds]");
  const index: { name: string; mode: string; icons: string; backgrounds: string[] }[] = [];
  for (const root of values.themes) {
    for (const name of (await readdir(root)).sort()) {
      const dir = join(root, name);
      if (!existsSync(join(dir, "colors.toml"))) continue;
      const colors = parseColors(await readFile(join(dir, "colors.toml"), "utf8"));
      const out = join(values.out, name);
      await mkdir(out, { recursive: true });
      const shipped = join(dir, "cosmic.ron");
      if (existsSync(shipped)) await copyFile(shipped, join(out, "cosmic.ron"));
      else if (
        !existsSync(join(out, "cosmic.ron")) ||
        !(await readFile(join(out, "cosmic.ron"), "utf8")).includes("Aphrody")
      )
        await writeFile(join(out, "cosmic.ron"), cosmicRon(name, colors));
      await writeFile(join(out, "rio.toml"), rioTheme(name, colors));
      const icons = iconTheme(
        existsSync(join(dir, "icons.theme")) ? await readFile(join(dir, "icons.theme"), "utf8") : undefined,
      );
      const bgDir = join(dir, "backgrounds");
      const backgrounds = existsSync(bgDir)
        ? (await readdir(bgDir, { withFileTypes: true }))
            .filter(e => e.isFile())
            .map(e => e.name)
            .sort()
        : [];
      if (values.backgrounds && backgrounds.length) {
        await mkdir(join(out, "backgrounds"), { recursive: true });
        for (const b of backgrounds) await copyFile(join(bgDir, b), join(out, "backgrounds", basename(b)));
      }
      const entry = { name, mode: colors.mode ?? "dark", icons, backgrounds };
      await writeFile(join(out, "theme.json"), JSON.stringify(entry, null, 2) + "\n");
      index.push(entry);
    }
  }
  // Themes generated elsewhere into --out (bunos-m3: `m3-os-themes apps`) have no Omarchy colors.toml; keep their entry.
  for (const name of (await readdir(values.out)).sort()) {
    const meta = join(values.out, name, "theme.json");
    if (index.some(e => e.name === name) || !existsSync(meta)) continue;
    index.push(JSON.parse(await readFile(meta, "utf8")));
  }
  await writeFile(join(values.out, "index.json"), JSON.stringify(index, null, 2) + "\n");
  console.log(`${index.length} themes -> ${values.out}`);
}

if (import.meta.main) await main();
