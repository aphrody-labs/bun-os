/**
 * Omarchy theme system on COSMIC. Every Omarchy theme (basecamp/omarchy themes/<name>/colors.toml, canonical
 * keys of docs/theming.md) becomes a COSMIC ThemeBuilder RON (pop-os/libcosmic cosmic-theme, #[version = 2])
 * plus the matching terminal (Rio), icon theme (Omarchy icons.theme) and wallpaper set, so `bunos-theme-set`
 * switches the whole COSMIC session the way `omarchy-theme-set` switches Hyprland.
 *
 *   bun factory/distro/cosmic-themes.ts --themes vendor/omarchy/themes --themes factory/distro/themes \
 *       --out factory/desktop/cosmic-session/rootfs/usr/share/bunos/themes [--backgrounds]
 *
 * Output per theme: cosmic.ron, rio.toml, theme.json. A theme directory that already ships cosmic.ron keeps it
 * (Aphrody's equals ThemeBuilder::dark() of the Bun OS libcosmic fork). --backgrounds also copies
 * backgrounds/* (image build time; the 150+ MB of Omarchy wallpapers stay out of Git).
 * Geometry is Omarchy's on every theme: Square corners, gaps (10, 10), 2 px active hint.
 */
import { existsSync } from "node:fs";
import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { parseArgs } from "node:util";
import { type Colors, mix, parseColors } from "./theme.ts";

