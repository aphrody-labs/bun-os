#!/usr/bin/env bun
// SPDX-License-Identifier: Apache-2.0
// Render factory/bunos/pkgbuilds/<name> for the emulators that have neither an Arch package nor a Bun OS fork: the
// pinned upstream Linux release binary (pins.json) repackaged under /opt/<name> with a desktop entry, icon, AppStream
// metainfo and the upstream license files. Forked emulators (vendor/dolphin, retroarch, melonds, azahar, pcsx2,
// gamescope, gopher64, tetanes, dxvk, vkd3d-proton) have hand-written PKGBUILDs that build the fork; mame and ares come
// from Arch.
//   bun factory/arch/emulators/render.ts
import { mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";

const here = import.meta.dir;
const pins = (await Bun.file(join(here, "pins.json")).json()) as Record<
  string,
  { repo: string; tag: string; asset: string; url: string; sha256: string }
>;

interface Spec {
  name: string;
  exe: string;
  license: string[];
  categories: string;
  mime?: string;
  /** "appimage" (also inside a zip), "binary" or "tarball". */
  kind: "appimage" | "binary" | "tarball";
  /** Executable inside a tarball. */
  member?: string;
  depends?: string[];
}
/** Package names match factory/images/bunos-gaming/emulation.packages. Excluded on purpose: duckstation (CC BY-NC-ND 4.0, no derivative builds) and jgenesis (32X boot ROM bytes match retail Sega BIOS hashes; see docs/bun-engine/FIRMWARE-AND-FORMATS.md). */
export const SPECS: Record<string, Spec> = {
  cemu: { name: "Cemu", exe: "Cemu", license: ["MPL-2.0"], categories: "Game;Emulator;", kind: "appimage" },
  rpcs3: { name: "RPCS3", exe: "rpcs3", license: ["GPL-2.0-only"], categories: "Game;Emulator;", kind: "appimage" },
  xemu: { name: "xemu", exe: "xemu", license: ["GPL-2.0-or-later"], categories: "Game;Emulator;", kind: "appimage" },
  flycast: {
    name: "Flycast",
    exe: "flycast",
    license: ["GPL-2.0-only"],
    categories: "Game;Emulator;",
    kind: "appimage",
  },
  "vita3k-bin": {
    name: "Vita3K",
    exe: "Vita3K",
    license: ["GPL-2.0-or-later"],
    categories: "Game;Emulator;",
    kind: "appimage",
  },
  shadps4: {
    name: "shadPS4",
    exe: "shadps4",
    license: ["GPL-2.0-or-later"],
    categories: "Game;Emulator;",
    kind: "appimage",
  },
};

const icon = (label: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><rect width="256" height="256" rx="56" fill="#381e72"/><rect x="40" y="88" width="176" height="96" rx="40" fill="#d0bcff"/><circle cx="92" cy="136" r="14" fill="#381e72"/><circle cx="168" cy="124" r="10" fill="#381e72"/><circle cx="188" cy="148" r="10" fill="#381e72"/><text x="128" y="64" font-family="sans-serif" font-size="36" font-weight="700" text-anchor="middle" fill="#eaddff">${label}</text></svg>\n`;

const out = join(here, "../../bunos/pkgbuilds");
for (const [id, spec] of Object.entries(SPECS)) {
  const pin = pins[id.replace(/-bin$/, "")];
  if (!pin) throw new Error(`${id}: no pin (run pin.ts)`);
  const pkgname = id;
  const pkgver =
    pin.tag
      .replace(/^[^0-9]*/, "")
      .replace(/[^A-Za-z0-9.]+/g, ".")
      .replace(/^\.|\.$/g, "") || "0";
  const dir = join(out, pkgname);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const isZip = pin.asset.endsWith(".zip");
  const desktop = `[Desktop Entry]
Type=Application
Name=${spec.name}
Comment=${spec.name} emulator (Bun OS package of ${pin.repo} ${pin.tag})
Exec=${spec.exe} %f
Icon=${pkgname}
Terminal=false
Categories=${spec.categories}
StartupWMClass=${spec.name}
`;
  await Bun.write(join(dir, `${pkgname}.desktop`), desktop);
  await Bun.write(join(dir, `${pkgname}.svg`), icon(spec.name.slice(0, 7)));
  await Bun.write(
    join(dir, `${pkgname}.metainfo.xml`),
    `<?xml version="1.0" encoding="UTF-8"?>
<component type="desktop-application">
  <id>com.aphrody.bunos.${pkgname}</id>
  <name>${spec.name}</name>
  <summary>${spec.name} emulator</summary>
  <metadata_license>CC0-1.0</metadata_license>
  <project_license>${spec.license.join(" OR ")}</project_license>
  <launchable type="desktop-id">${pkgname}.desktop</launchable>
  <url type="homepage">https://github.com/${pin.repo}</url>
  <categories><category>Game</category><category>Emulator</category></categories>
  <releases><release version="${pkgver}"/></releases>
  <content_rating type="oars-1.1"/>
</component>
`,
  );
  const common = `# SPDX-License-Identifier: Apache-2.0
# Generated by factory/arch/emulators/render.ts from pins.json; edit those, not this file.
pkgname=${pkgname}
pkgver=${pkgver}
pkgrel=1
pkgdesc="${spec.name} emulator, upstream ${pin.repo} ${pin.tag} release binary packaged for Bun OS"
arch=(x86_64)
url="https://github.com/${pin.repo}"
license=(${spec.license.map(l => `'${l}'`).join(" ")})
depends=(${["glibc", "hicolor-icon-theme", ...(spec.depends ?? [])].map(d => `'${d}'`).join(" ")})
options=('!strip' '!debug')
source=("${pin.asset}::${pin.url}" "${pkgname}.desktop" "${pkgname}.svg" "${pkgname}.metainfo.xml")
sha256sums=('${pin.sha256}' 'SKIP' 'SKIP' 'SKIP')
${spec.kind === "appimage" && !isZip ? `noextract=("${pin.asset}")\n` : ""}`;
  const desktopAndIcon = `  install -Dm644 "$srcdir/${pkgname}.desktop" "$pkgdir/usr/share/applications/${pkgname}.desktop"
  install -Dm644 "$srcdir/${pkgname}.svg" "$pkgdir/usr/share/icons/hicolor/scalable/apps/${pkgname}.svg"
  install -Dm644 "$srcdir/${pkgname}.metainfo.xml" "$pkgdir/usr/share/metainfo/com.aphrody.bunos.${pkgname}.metainfo.xml"`;
  const body =
    spec.kind === "appimage"
      ? `prepare() {
  cd "$srcdir"
  local image
  image=$(find . -maxdepth 2 -iname '*.AppImage' | head -n1)
  chmod +x "$image"
  rm -rf squashfs-root
  "$image" --appimage-extract >/dev/null
}

package() {
  install -d "$pkgdir/opt/${pkgname}" "$pkgdir/usr/bin"
  cp -a "$srcdir/squashfs-root/." "$pkgdir/opt/${pkgname}/"
  chmod -R u+rwX,go+rX "$pkgdir/opt/${pkgname}"
  printf '#!/bin/sh\\nexec /opt/${pkgname}/AppRun "$@"\\n' > "$pkgdir/usr/bin/${spec.exe}"
  chmod 755 "$pkgdir/usr/bin/${spec.exe}"
${desktopAndIcon}
  # Upstream license and notice files shipped inside the image.
  install -d "$pkgdir/usr/share/licenses/${pkgname}"
  find "$srcdir/squashfs-root" -maxdepth 4 -type f \\( -iname 'LICENSE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \\) -exec cp -n {} "$pkgdir/usr/share/licenses/${pkgname}/" \\; || true
  printf '%s\\n' "Upstream: ${pin.url}" "sha256: ${pin.sha256}" "License: ${spec.license.join(" OR ")}" > "$pkgdir/usr/share/licenses/${pkgname}/SOURCE"
}
`
      : `package() {
  cd "$srcdir"
  install -Dm755 "${spec.kind === "binary" ? pin.asset : `$(find . -type f -name '${spec.member}' | head -n1)`}" "$pkgdir/usr/bin/${spec.exe}"
${desktopAndIcon}
  install -d "$pkgdir/usr/share/licenses/${pkgname}"
  find . -maxdepth 3 -type f \\( -iname 'LICENSE*' -o -iname 'COPYING*' \\) -exec cp -n {} "$pkgdir/usr/share/licenses/${pkgname}/" \\; || true
  printf '%s\\n' "Upstream: ${pin.url}" "sha256: ${pin.sha256}" "License: ${spec.license.join(" OR ")}" > "$pkgdir/usr/share/licenses/${pkgname}/SOURCE"
}
`;
  await Bun.write(join(dir, "PKGBUILD"), `${common}\n${body}`);
}
console.log(`rendered ${Object.keys(SPECS).length} PKGBUILDs into ${out}`);
