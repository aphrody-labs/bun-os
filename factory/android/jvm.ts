// JVM, Kotlin, Gradle and Flutter side of the shared Bun OS Android toolchain, pinned in jvm.json.
// factory/android/sdk.ts owns /opt/android-sdk (SDK, NDK, emulator images); this recipe never writes there.
//   bun factory/android/jvm.ts install   JDKs (apt), shared Gradle user home + gradle.properties, cargo-ndk, Rust Android
//                                        targets, Flutter fork checkout (vendor/flutter) configured for the shared SDK
//   bun factory/android/jvm.ts verify    prints every pinned tool and its measured version; exit 1 on drift
//   bun factory/android/jvm.ts env       shell exports (JAVA_HOME, GRADLE_USER_HOME, PUB_CACHE, PATH) for `eval`
// Linux only (the VPS and build containers). Licences are accepted non-interactively: the owner accepted them all.
import { existsSync, mkdirSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

interface Jdk {
  major: number;
  home: string;
  package: string;
}
export interface JvmRecipe {
  jdk: { agp: Jdk; lts: Jdk };
  gradle: { version: string; distributionSha256: string; userHome: string; properties: Record<string, string> };
  kotlin: { version: string; url: string };
  android: { agp: string; abis: string[] };
  rust: { cargoNdk: string; flutterRustBridge: string };
  flutter: { fork: string; branch: string; version: string; revision: string; path: string; pubCache: string };
}

export const recipe: JvmRecipe = await Bun.file(join(import.meta.dir, "jvm.json")).json();
const root = resolve(import.meta.dir, "..", "..");
const expand = (p: string) => (p.startsWith("~/") ? join(homedir(), p.slice(2)) : p);
export const gradleUserHome = expand(process.env.GRADLE_USER_HOME ?? recipe.gradle.userHome);
export const pubCache = expand(process.env.PUB_CACHE ?? recipe.flutter.pubCache);
export const flutterRoot = join(root, recipe.flutter.path);
const sdk = process.env.ANDROID_HOME ?? "/opt/android-sdk";
const RUST_TARGETS = ["aarch64-linux-android", "armv7-linux-androideabi", "i686-linux-android", "x86_64-linux-android"];

/** Environment every JVM/Gradle/Flutter command of the factory runs with. */
export function jvmEnv(): Record<string, string> {
  return {
    JAVA_HOME: recipe.jdk.agp.home,
    GRADLE_USER_HOME: gradleUserHome,
    PUB_CACHE: pubCache,
    ANDROID_HOME: sdk,
    ANDROID_SDK_ROOT: sdk,
    FLUTTER_ROOT: flutterRoot,
    // The pinned fork is the upstream of vendor/flutter: tell the tool so doctor stays clean.
    FLUTTER_GIT_URL: recipe.flutter.fork,
    // cargo-ndk only runs as a Cargo subcommand; CARGO names the cargo it drives (cargo-serial in Gradle builds).
    CARGO: process.env.CARGO ?? "cargo",
    FLUTTER_SUPPRESS_ANALYTICS: "true",
    DART_SUPPRESS_ANALYTICS: "true",
    PATH: [
      join(recipe.jdk.agp.home, "bin"),
      join(flutterRoot, "bin"),
      join(sdk, "platform-tools"),
      join(homedir(), ".cargo", "bin"),
      process.env.PATH,
    ].join(":"),
  };
}

async function sh(
  cmd: string[],
  opts: { env?: Record<string, string>; cwd?: string; allowFail?: boolean } = {},
): Promise<{ code: number; out: string }> {
  const proc = Bun.spawn(cmd, {
    cwd: opts.cwd,
    env: { ...process.env, ...opts.env },
    stdout: "pipe",
    stderr: "pipe",
    stdin: "ignore",
  });
  const [out, err, code] = await Promise.all([proc.stdout.text(), proc.stderr.text(), proc.exited]);
  if (code !== 0 && !opts.allowFail)
    throw new Error(`${cmd.join(" ")} failed (${code}): ${(err || out).trim().split("\n").slice(-5).join("\n")}`);
  return { code, out: `${out}${err}` };
}

/** gradle.properties of the shared Gradle user home: overrides every project's own memory/parallel settings. */
export function gradleProperties(): string {
  return `# GENERATED by factory/android/jvm.ts from jvm.json. Shared by every Gradle build of the Bun OS factory.\n${Object.entries(
    recipe.gradle.properties,
  )
    .map(([k, v]) => `${k}=${v}`)
    .join("\n")}\n`;
}

async function installJdks() {
  const missing = [recipe.jdk.agp, recipe.jdk.lts].filter(j => !existsSync(join(j.home, "bin", "javac")));
  if (missing.length)
    await sh(["sudo", "-n", "apt-get", "install", "-y", "--no-install-recommends", ...missing.map(j => j.package)]);
}

async function installGradleHome() {
  mkdirSync(gradleUserHome, { recursive: true });
  await Bun.write(join(gradleUserHome, "gradle.properties"), gradleProperties());
}

async function installRust() {
  if (!Bun.which("rustup")) return;
  await sh(["rustup", "target", "add", ...RUST_TARGETS]);
  const have = await sh(["cargo-ndk", "ndk", "--version"], { env: { CARGO: "cargo" }, allowFail: true }).catch(() => ({
    code: 1,
    out: "",
  }));
  if (!have.out.includes(recipe.rust.cargoNdk))
    await sh(["cargo", "install", "--locked", "cargo-ndk", "--version", recipe.rust.cargoNdk]);
}

async function installFlutter() {
  const env = jvmEnv();
  if (!existsSync(join(flutterRoot, "bin", "flutter"))) {
    // Blobless clone of the pinned fork branch; history stays available on demand.
    await sh([
      "git",
      "clone",
      "--filter=blob:none",
      "--branch",
      recipe.flutter.branch,
      recipe.flutter.fork,
      flutterRoot,
    ]);
  }
  await sh(["git", "-C", flutterRoot, "fetch", "--filter=blob:none", "origin", recipe.flutter.branch, "--tags"]);
  await sh(["git", "-C", flutterRoot, "checkout", "-q", recipe.flutter.revision]);
  // The tool reads the channel from the branch name; keep a local `stable` branch on the pinned revision.
  await sh(["git", "-C", flutterRoot, "branch", "-f", recipe.flutter.branch, recipe.flutter.revision], {
    allowFail: true,
  });
  await sh(["git", "-C", flutterRoot, "checkout", "-q", recipe.flutter.branch]);
  mkdirSync(pubCache, { recursive: true });
  const flutter = join(flutterRoot, "bin", "flutter");
  await sh([flutter, "--disable-analytics"], { env, allowFail: true });
  await sh(
    [
      flutter,
      "config",
      "--android-sdk",
      sdk,
      "--jdk-dir",
      recipe.jdk.agp.home,
      "--enable-android",
      "--enable-linux-desktop",
      "--enable-web",
      "--no-cli-animations",
    ],
    { env },
  );
  await sh([flutter, "precache", "--android", "--linux", "--web"], { env });
  await sh(["bash", "-c", `yes | ${flutter} doctor --android-licenses`], { env, allowFail: true });
}

async function version(cmd: string[], pattern: RegExp): Promise<string> {
  const r = await sh(cmd, { env: jvmEnv(), allowFail: true }).catch(() => ({ code: 1, out: "" }));
  return pattern.exec(r.out)?.[1] ?? "-";
}

export async function verify(): Promise<boolean> {
  const rows: [string, string, string][] = [
    [
      "jdk-agp",
      String(recipe.jdk.agp.major),
      await version([join(recipe.jdk.agp.home, "bin", "javac"), "-version"], /javac (\d+)/),
    ],
    [
      "jdk-lts",
      String(recipe.jdk.lts.major),
      await version([join(recipe.jdk.lts.home, "bin", "javac"), "-version"], /javac (\d+)/),
    ],
    ["libjvm-lts", "present", existsSync(join(recipe.jdk.lts.home, "lib", "server", "libjvm.so")) ? "present" : "-"],
    [
      "gradle.properties",
      "present",
      existsSync(join(gradleUserHome, "gradle.properties")) &&
      (await Bun.file(join(gradleUserHome, "gradle.properties")).text()) === gradleProperties()
        ? "present"
        : "-",
    ],
    ["cargo-ndk", recipe.rust.cargoNdk, await version(["cargo-ndk", "ndk", "--version"], /cargo-ndk (\S+)/)],
    [
      "flutter",
      recipe.flutter.version,
      await version([join(flutterRoot, "bin", "flutter"), "--version", "--machine"], /"frameworkVersion":\s*"([^"]+)"/),
    ],
  ];
  let ok = true;
  for (const [name, want, have] of rows) {
    const good = have === want || have.startsWith(`${want}.`);
    if (!good) ok = false;
    console.log(`${good ? "ok  " : "BAD "} ${name} want ${want} have ${have}`);
  }
  return ok;
}

if (import.meta.main) {
  const [command = "verify"] = process.argv.slice(2);
  switch (command) {
    case "install":
      await installJdks();
      await installGradleHome();
      await installRust();
      await installFlutter();
      if (!(await verify())) process.exit(1);
      break;
    case "gradle-home":
      await installGradleHome();
      break;
    case "flutter":
      await installFlutter();
      break;
    case "verify":
      if (!(await verify())) process.exit(1);
      break;
    case "env":
      for (const [k, v] of Object.entries(jvmEnv())) console.log(`export ${k}=${JSON.stringify(v)}`);
      break;
    default:
      console.error(`unknown command ${command}`);
      process.exit(2);
  }
}
