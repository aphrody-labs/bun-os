/**
 * Writes the Bun OS desktop PKGBUILDs whose source is a pinned aphrody-labs fork: the Rust CLI stack from
 * factory/desktop/cli.json and the `bunos-cli` meta-package. The pin is the gitlink of the vendor path (git ls-tree
 * HEAD) and the URL its .gitmodules entry, so bumping a fork is: move the gitlink, rerun this, commit.
 *
 *   bun factory/desktop/pkgbuilds.ts            write factory/desktop/pkgbuilds/<pkg>/PKGBUILD
 *   bun factory/desktop/pkgbuilds.ts --check    exit 1 when a written PKGBUILD differs (stale pin)
 *
 * The hand-maintained recipes (compositors, GNOME, bunos-desktop, bunos-omarchy) live beside them; their
 * `_commit=` lines are checked against the gitlinks with --check as well.
 */
import { $ } from "bun";
import { existsSync, readdirSync } from "node:fs";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dir, "../..");
const out = join(import.meta.dir, "pkgbuilds");
const check = Bun.argv.includes("--check");

interface Tool {
  pkg: string;
  vendor: string;
  license: string;
  desc: string;
  release: string;
  bins?: string[];
  cargo?: string;
  env?: string;
  build?: string;
  install?: string;
  extra?: string;
  depends?: string[];
  makedepends?: string[];
}

const gitmodules = await Bun.file(join(root, ".gitmodules")).text();
export function forkUrl(path: string): string {
  const m = gitmodules.match(new RegExp(`\\[submodule "${path}"\\][^\\[]*?url = (\\S+)`));
  if (!m) throw new Error(`${path}: no .gitmodules entry`);
  return m[1]!.replace(/\.git$/, "") + ".git";
}
/** The gitlink commit of `path`; a path inside a submodule (vendor/cosmic-epoch/cosmic-comp) is resolved in that
 * submodule's pinned tree, which needs the outer submodule checked out. */
export async function pin(path: string, repo = root, rev = "HEAD"): Promise<string> {
  const line = (await $`git -C ${repo} ls-tree ${rev} ${path}`.text()).trim();
  const m = line.match(/^160000 commit ([0-9a-f]{40})\t/);
  if (m) return m[1]!;
  const parts = path.split("/");
  for (let i = parts.length - 1; i > 0; i--) {
    const outer = parts.slice(0, i).join("/");
    const o = (await $`git -C ${repo} ls-tree ${rev} ${outer}`.text()).trim().match(/^160000 commit ([0-9a-f]{40})\t/);
    if (o) return pin(parts.slice(i).join("/"), join(repo, outer), o[1]!);
  }
  throw new Error(`${path}: not a gitlink at ${rev}`);
}

const arr = (xs: string[]) => xs.map(x => `'${x}'`).join(" ");
const PKGVER = `pkgver() {
  cd "$pkgname"
  # Only release-looking tags count (yazi also tags "nightly" on release commits).
  local m=(--match 'v[0-9]*' --match '[0-9]*') v
  if v=$(git describe --tags --exact-match "\${m[@]}" 2>/dev/null); then
    v=$(sed 's/^v//; s/-/./g' <<<"$v")
  elif v=$(git describe --tags --long "\${m[@]}" 2>/dev/null); then
    v=$(sed 's/^v//; s/-\\([0-9]*\\)-g/.r\\1.g/; s/-/./g' <<<"$v")
  else
    v=r$(git rev-list --count HEAD).$(git rev-parse --short=12 HEAD)
  fi
  printf '%s' "$v"
}`;

function toolPkgbuild(t: Tool, url: string, commit: string): string {
  const env = t.env ? `export ${t.env}\n  ` : "";
  const build = t.build ?? `cargo build --frozen --release ${t.cargo ?? ""}`.trim();
  const install =
    t.install ?? (t.bins ?? []).map(b => `install -Dm755 "target/release/${b}" "$pkgdir/usr/bin/${b}"`).join("\n  ");
  return `# Generated by factory/desktop/pkgbuilds.ts from factory/desktop/cli.json; do not edit.
# Source: ${url} at the gitlink ${t.vendor} (upstream release ${t.release}).
pkgname=${t.pkg}
pkgver=0
pkgrel=1
pkgdesc='${t.desc} (Bun OS, built from the aphrody-labs fork)'
arch=(x86_64)
url='${url.replace(/\.git$/, "")}'
license=('${t.license}')
depends=(${arr(["gcc-libs", "glibc", ...(t.depends ?? [])])})
makedepends=(${arr(["cargo", "git", ...(t.makedepends ?? [])])})
options=(!lto)
source=("$pkgname::git+${url}#commit=${commit}")
b2sums=('SKIP')

${PKGVER}

prepare() {
  cd "$pkgname"
  export RUSTUP_TOOLCHAIN=stable
  cargo fetch --locked --target "$(rustc -vV | sed -n 's/host: //p')"
}

build() {
  cd "$pkgname"
  export RUSTUP_TOOLCHAIN=stable CARGO_TARGET_DIR=target
  ${env}${build}
}

package() {
  cd "$pkgname"
  ${install}${t.extra ? `\n  ${t.extra}` : ""}
  for f in LICENSE* COPYING* UNLICENSE*; do
    [[ -f $f ]] && install -Dm644 "$f" "$pkgdir/usr/share/licenses/$pkgname/$f"
  done
  true
}
`;
}

function metaPkgbuild(tools: Tool[]): string {
  return `# Generated by factory/desktop/pkgbuilds.ts from factory/desktop/cli.json; do not edit.
pkgname=bunos-cli
pkgver=2026.11.03
pkgrel=1
pkgdesc='Bun OS default Rust CLI stack (meta-package; every tool built from its aphrody-labs fork)'
arch=(any)
url='https://github.com/aphrody-labs/bun-os'
license=('Apache-2.0')
depends=(
${tools.map(t => `  '${t.pkg}'`).join("\n")}
)
`;
}

const { tools } = (await Bun.file(join(import.meta.dir, "cli.json")).json()) as { tools: Tool[] };
const files = new Map<string, string>();
for (const t of tools) files.set(t.pkg, toolPkgbuild(t, forkUrl(t.vendor), await pin(t.vendor)));
files.set("bunos-cli", metaPkgbuild(tools));

let stale = 0;
for (const [pkg, text] of files) {
  const path = join(out, pkg, "PKGBUILD");
  const cur = existsSync(path) ? await Bun.file(path).text() : "";
  if (cur === text) continue;
  if (check) {
    console.error(`stale: ${path}`);
    stale++;
  } else {
    await mkdir(join(out, pkg), { recursive: true });
    await Bun.write(path, text);
    console.log(`wrote ${pkg}`);
  }
}

// Hand-maintained recipes: `# vendor: <path>` + `_commit=<sha>` must match the gitlink.
for (const pkg of readdirSync(out)) {
  const path = join(out, pkg, "PKGBUILD");
  if (files.has(pkg) || !existsSync(path)) continue;
  const text = await Bun.file(path).text();
  for (const m of text.matchAll(/^# vendor: (\S+) -> (_\w+)$/gm)) {
    const want = await pin(m[1]!);
    const got = text.match(new RegExp(`^${m[2]}=([0-9a-f]{40})$`, "m"))?.[1];
    if (got !== want) {
      console.error(`${pkg}: ${m[2]}=${got} but ${m[1]} is ${want}`);
      stale++;
    }
  }
}
if (stale) process.exit(1);
