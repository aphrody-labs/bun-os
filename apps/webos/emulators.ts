// Every emulator of the repository and how WebOS serves and tests it. Shared by the worker
// (/api/emulators), the Emulators app and the qualification runner
// (packages/bun-engine/web-emulation/qualify-webos.ts). Sources of truth for ownership:
// packages/bun-engine/plugins/consoles/{manifest,releases,systems}.json and
// packages/bun-engine/web-emulation/recipes.json; this list only adds the WebOS delivery mode.

/**
 * wasm: runs in the browser from /emulation/<core>/ and is qualified by booting a free ROM.
 * v86: the x86 machine of the Alpine Linux app, qualified through its serial console.
 * native: no WebAssembly build exists; the entry is a real status surface with the blocker.
 */
export type EmulatorMode = "wasm" | "v86" | "native";

export interface EmulatorFixture {
  /** Fixture pack id (roms.json id or a generated pack). */
  pack: string;
  file: string;
  license: string;
  source: string;
  /** `system` option the core is started with. */
  system: string;
  /** Free firmware id of free-firmware.json the core needs, if any. */
  firmware?: string;
}

export interface Emulator {
  id: string;
  name: string;
  /** bun-engine system ids. */
  systems: string[];
  mode: EmulatorMode;
  /** Repository owner path of the source. */
  owner: string;
  license?: string;
  /** Served core directory under /emulation/ (wasm). */
  core?: string;
  fixture?: EmulatorFixture;
  /** Why an entry is not a browser build, or what remains. */
  reason?: string;
}

