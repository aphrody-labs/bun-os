/**
 * Every place that paints before a stylesheet loads carries the colours of
 * the generated Material 3 sheet, written by sheet/generate.ts and never by
 * hand: the boot screens and the theme switch (the SHEET block of
 * src/lib/fatal-error.ts), the loading
 * screen (public/first-paint.css), the remote page (mobile-client/styles.css),
 * the iOS window (tauri.ios.conf.json) and the Android window (StartTheme.kt).
 *
 * A changed sheet without a regenerate shows up here as a stale output.
 */
import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { OUTPUTS, SOURCES, readSheet, render, stale } from '../sheet/generate'
import { SHEET } from '../../../lib/fatal-error'

const read = (path: string): string => readFileSync(path, 'utf8')
const sheet = readSheet(read(SOURCES.tokens), read(SOURCES.tailwind))

describe('the generated sheet constants', () => {
  it('every output is what the sheet gives (run bun src/mobile/styles/sheet/generate.ts)', () => {
    expect(stale()).toEqual([])
  })

  it('the boot module holds the surface role of both schemes, inside its generated block', () => {
    const src = read(OUTPUTS.module)
    const begin = src.indexOf('// m3-sheet:begin, generated by')
    const end = src.indexOf('// m3-sheet:end')
    expect(begin).toBeGreaterThanOrEqual(0)
    expect(end).toBeGreaterThan(begin)
    // Outside the block the file names no colour.
    const rest = (src.slice(0, begin) + src.slice(end)).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')
    expect(rest).not.toMatch(/#[0-9a-fA-F]{3,8}\b|rgba?\(/)
    expect(SHEET.light.surface).toBe(sheet.light.surface)
    expect(SHEET.dark.surface).toBe(sheet.dark.surface)
    expect(SHEET.light.surface).not.toBe(SHEET.dark.surface)
  })

  it('the loading screen paints the surface role for each mark', () => {
    const css = read(OUTPUTS.firstPaint)
    expect(css).toContain('generated by')
    expect(css).toContain(`html.lu-first-light #splash { background: ${sheet.light.surface} !important; }`)
    expect(css).toContain(`html.lu-first-dark #splash { background: ${sheet.dark.surface} !important; }`)
  })

  it('the native windows start on the dark and light surface', () => {
    const conf = JSON.parse(read(OUTPUTS.iosConf))
    expect(conf.app.windows[0].backgroundColor).toBe(sheet.dark.surface)
    const kotlin = read(OUTPUTS.startTheme)
    const argb = (hex: string): string => `0xFF${hex.slice(1).toUpperCase()}`
    expect(kotlin).toContain(`const val CANVAS_LIGHT: Int = ${argb(sheet.light.surface)}.toInt()`)
    expect(kotlin).toContain(`const val CANVAS_DARK: Int = ${argb(sheet.dark.surface)}.toInt()`)
  })

  it('the remote page reads roles, declared once in its generated block', () => {
    const css = read(OUTPUTS.mobileClient)
    const begin = css.indexOf('/* m3-sheet:begin')
    const end = css.indexOf('/* m3-sheet:end */')
    expect(begin).toBeGreaterThanOrEqual(0)
    expect(end).toBeGreaterThan(begin)
    const rest = (css.slice(0, begin) + css.slice(end)).replace(/\/\*[\s\S]*?\*\//g, '')
    const literals = rest
      .split('\n')
      .filter((line) => /#[0-9a-fA-F]{3,8}\b|rgba?\(/.test(line))
    // The one literal left is the white ground of the HTML preview frame, marked as content.
    expect(literals).toEqual(['.html-preview-frame{flex:1;width:100%;border:none;background:#ffffff;display:block} '])
    expect(css.slice(begin, end)).toContain(`--md-sys-color-surface:${sheet.dark.surface};`)
  })

  it('render is pure: it only reads, and the same input gives the same output', () => {
    const files = new Map<string, string>()
    const memo = (path: string): string => {
      if (!files.has(path)) files.set(path, read(path))
      return files.get(path)!
    }
    const a = render(memo)
    const b = render(memo)
    expect([...a.entries()]).toEqual([...b.entries()])
  })
})
