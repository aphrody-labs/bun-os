/**
 * The colours of every place that paints before a stylesheet can load, taken
 * from the generated Material 3 sheet and never copied by hand.
 *
 * `@aphrody/m3-theme/tokens.css` is the scheme of the app (light in `:root`,
 * dark in `.dark`), `@aphrody/m3-theme/tailwind.css` carries the extended
 * success and warning roles. Five places cannot read either sheet:
 *
 *   - the SHEET block of `src/lib/fatal-error.ts`  the boot error screens and
 *     the phone theme switch (`theme-color`, the html background); it lives
 *     in src/lib because the desktop bundle may not import from src/mobile
 *   - `public/first-paint.css`         the loading screen of the phone
 *   - `mobile-client/styles.css`       the remote page, which is one Rust
 *     string with no stylesheet links (`src-tauri/src/mobile_page.rs`)
 *   - `src-tauri/tauri.ios.conf.json`  what wry paints on iOS before the page
 *   - `StartTheme.kt` of the native plugin, found through the path
 *     dependencies of src-tauri/Cargo.toml: the Android window before the page
 *
 * Run `bun src/mobile/styles/sheet/generate.ts` after the sheet changed;
 * `--check` exits non-zero when any output is stale (also asserted by
 * `src/mobile/styles/__tests__/sheet.test.ts`).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
export const APP = resolve(HERE, '../../../..')

/** The sheets, resolved through the declared dependency like the bundler does. */
const fromApp = createRequire(resolve(APP, 'package.json'))
export const SOURCES = {
  tokens: fromApp.resolve('@aphrody/m3-theme/tokens.css'),
  tailwind: fromApp.resolve('@aphrody/m3-theme/tailwind.css'),
}

const START_THEME = 'android/src/main/java/com/purpledoubled/lunative/StartTheme.kt'

/** The native plugin is a path dependency of the app's Rust crate; StartTheme.kt lives in it. */
function startThemeFile(): string {
  const manifest = resolve(APP, 'src-tauri/Cargo.toml')
  const deps = [...readFileSync(manifest, 'utf8').matchAll(/\bpath\s*=\s*"([^"]+)"/g)].map((m) => resolve(dirname(manifest), m[1]))
  const hit = deps.map((dir) => resolve(dir, START_THEME)).find((file) => existsSync(file))
  if (!hit) throw new Error(`no path dependency of ${manifest} carries ${START_THEME}`)
  return hit
}

export const OUTPUTS = {
  module: resolve(APP, 'src/lib/fatal-error.ts'),
  firstPaint: resolve(APP, 'public/first-paint.css'),
  mobileClient: resolve(APP, 'mobile-client/styles.css'),
  iosConf: resolve(APP, 'src-tauri/tauri.ios.conf.json'),
  startTheme: startThemeFile(),
}

const HEADER = 'generated by apps/lu/src/mobile/styles/sheet/generate.ts from @aphrody/m3-theme. Do not edit.'
const BEGIN = '/* m3-sheet:begin, ' + HEADER + ' */'
const END = '/* m3-sheet:end */'
const TS_BEGIN = '// m3-sheet:begin, ' + HEADER
const TS_END = '// m3-sheet:end'

export type Scheme = Record<string, string>
export interface Sheet {
  light: Scheme
  dark: Scheme
}

function declarations(body: string): Scheme {
  const out: Scheme = {}
  for (const m of body.matchAll(/--md-(?:sys|ext)-color-([a-z-]+)\s*:\s*(#[0-9a-fA-F]{6})\s*;/g)) out[m[1]] = m[2].toLowerCase()
  return out
}

function block(css: string, selector: RegExp, what: string): string {
  const m = selector.exec(css)
  if (!m) throw new Error(`${what} is missing from the sheet`)
  const open = css.indexOf('{', m.index)
  const close = css.indexOf('}', open)
  return css.slice(open + 1, close)
}

/** The light and dark schemes, each with every M3 role plus the extended roles. */
export function readSheet(tokensCss: string, tailwindCss: string): Sheet {
  const light = declarations(block(tokensCss, /^:root\s*\{/m, 'the light :root block'))
  const dark = declarations(block(tokensCss, /^:root\.dark,\s*\n\.dark\s*\{/m, 'the .dark block'))
  const extLight = declarations(block(tailwindCss, /^:where\(:root\)\s*\{/m, 'the light extended roles'))
  const extDark = declarations(block(tailwindCss, /^ {2,}:where\(:root\)\s*\{/m, 'the dark extended roles'))
  const sheet = { light: { ...light, ...extLight }, dark: { ...dark, ...extDark } }
  for (const role of ['surface', 'on-surface', 'on-surface-variant', 'error', 'success', 'primary']) {
    if (!sheet.light[role] || !sheet.dark[role]) throw new Error(`role ${role} is missing from the sheet`)
  }
  return sheet
}

/** Roles the boot screens and the theme switch need, camel-cased. */
const MODULE_ROLES = [
  'surface',
  'on-surface',
  'on-surface-variant',
  'surface-container',
  'surface-container-high',
  'surface-container-highest',
  'outline',
  'outline-variant',
  'error',
  'primary',
  'on-primary',
  'scrim',
] as const

const camel = (role: string): string => role.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())

/** The SHEET constant inside fatal-error.ts, between its markers. */
function spliceModule(current: string, sheet: Sheet): string {
  const scheme = (s: Scheme): string =>
    `{\n${MODULE_ROLES.map((r) => `    ${camel(r)}: '${s[r]}',`).join('\n')}\n  }`
  const block = `${TS_BEGIN}
// The Material 3 roles for code that runs before any stylesheet is loaded or
// after it failed: the boot error screens and the theme switch of the phone.
export const SHEET = {
  light: ${scheme(sheet.light)},
  dark: ${scheme(sheet.dark)},
} as const
${TS_END}`
  const from = current.indexOf('// m3-sheet:begin')
  const to = current.indexOf(TS_END)
  if (from === -1 || to === -1) throw new Error('src/lib/fatal-error.ts has no m3-sheet block')
  return current.slice(0, from) + block + current.slice(to + TS_END.length)
}

function renderFirstPaint(sheet: Sheet): string {
  return `/* ${HEADER}
   The ground of the phone shell from the first frame, light or dark: the
   surface role of the sheet. public/first-paint.js marks <html> on a phone,
   and only there, so nothing in this file matches on a desktop. A file and
   not a <style> block because Tauri nonces every <style> element, which
   switches 'unsafe-inline' off for the style attributes of index.html. */
html.lu-first-light,
html.lu-first-light body,
html.lu-first-light #splash { background: ${sheet.light.surface} !important; }
html.lu-first-light #splash img { filter: invert(1); }
html.lu-first-light #splash div { color: ${sheet.light['on-surface-variant']} !important; }
html.lu-first-dark,
html.lu-first-dark body,
html.lu-first-dark #splash { background: ${sheet.dark.surface} !important; }
html.lu-first-dark #splash div { color: ${sheet.dark['on-surface-variant']} !important; }
`
}

const CLIENT_ROLES = [
  'surface',
  'on-surface',
  'on-surface-variant',
  'surface-container-low',
  'surface-container',
  'surface-container-high',
  'surface-container-highest',
  'primary',
  'on-primary',
  'primary-container',
  'on-primary-container',
  'secondary',
  'secondary-container',
  'on-secondary-container',
  'tertiary',
  'tertiary-container',
  'on-tertiary-container',
  'error',
  'on-error',
  'error-container',
  'on-error-container',
  'outline',
  'outline-variant',
  'inverse-surface',
  'inverse-on-surface',
  'scrim',
  'shadow',
  'success',
  'success-container',
  'on-success-container',
] as const

function clientVars(s: Scheme): string {
  return CLIENT_ROLES.map((r) => `--md-sys-color-${r}:${s[r]};`).join('')
}

/** The role block of the remote page; the page has dark as its default ground. */
function renderClientBlock(sheet: Sheet): string {
  return `${BEGIN}
:root{${clientVars(sheet.dark)}}
@media (prefers-color-scheme: light){:root{${clientVars(sheet.light)}}}
${END}`
}

function spliceClient(current: string, sheet: Sheet): string {
  const from = current.indexOf('/* m3-sheet:begin')
  const to = current.indexOf(END)
  const block = renderClientBlock(sheet)
  if (from === -1 || to === -1) throw new Error('mobile-client/styles.css has no m3-sheet block')
  return current.slice(0, from) + block + current.slice(to + END.length)
}

function renderIosConf(current: string, sheet: Sheet): string {
  return current.replace(/("backgroundColor":\s*)"#[0-9a-fA-F]{6}"/, `$1"${sheet.dark.surface}"`)
}

const argb = (hex: string): string => `0xFF${hex.slice(1).toUpperCase()}`

function renderStartTheme(current: string, sheet: Sheet): string {
  return current
    .replace(/(const val CANVAS_LIGHT: Int = )0xFF[0-9A-Fa-f]{6}(\.toInt\(\))/, `$1${argb(sheet.light.surface)}$2`)
    .replace(/(const val CANVAS_DARK: Int = )0xFF[0-9A-Fa-f]{6}(\.toInt\(\))/, `$1${argb(sheet.dark.surface)}$2`)
}

/** Every output as it has to be on disk, given the current files. */
export function render(read: (path: string) => string = (p) => readFileSync(p, 'utf8')): Map<string, string> {
  const sheet = readSheet(read(SOURCES.tokens), read(SOURCES.tailwind))
  return new Map([
    [OUTPUTS.module, spliceModule(read(OUTPUTS.module), sheet)],
    [OUTPUTS.firstPaint, renderFirstPaint(sheet)],
    [OUTPUTS.mobileClient, spliceClient(read(OUTPUTS.mobileClient), sheet)],
    [OUTPUTS.iosConf, renderIosConf(read(OUTPUTS.iosConf), sheet)],
    [OUTPUTS.startTheme, renderStartTheme(read(OUTPUTS.startTheme), sheet)],
  ])
}

/** Outputs whose file differs from what the sheet gives. */
export function stale(read: (path: string) => string = (p) => readFileSync(p, 'utf8')): string[] {
  const out: string[] = []
  for (const [path, text] of render(read)) {
    let current = ''
    try {
      current = read(path)
    } catch {
      current = ''
    }
    if (current !== text) out.push(path)
  }
  return out
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const old = stale()
    if (old.length > 0) {
      console.error(`stale, run bun src/mobile/styles/sheet/generate.ts:\n${old.join('\n')}`)
      process.exit(1)
    }
  } else {
    for (const [path, text] of render()) writeFileSync(path, text)
  }
}
